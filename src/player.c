/* Original: FUN_800ACDA0. Exact 0x800ACDA0..0x800ACF98: push the player out of a moving box. */
__declspec(noinline) void player_push_out_of_box(sint32 x, sint32 y, sint32 z, sint32 half_x, sint32 height, sint32 half_z)
{
    PLAYER *player = g_player;
    sint32 left = x - half_x, right = x + half_x;
    sint32 top = y - div_pow2_trunc(height, 1), bottom = y + div_pow2_trunc(height, 1);
    sint32 back = z - half_z, front = z + half_z;
    sint32 old_x = player->x - g_player_displacement_x;
    sint32 old_y = player->y - g_player_displacement_y;
    sint32 old_z = player->z - g_player_displacement_z;
    if (g_player_world_y < top || bottom < g_player_world_y || g_player_world_x <= left || right <= g_player_world_x || g_player_world_z <= back || front <= g_player_world_z)
        return;
    if (g_scuba_stage_active)
    {
        if (old_y < top)
        {
            player->y = top - 0x100;
            return;
        }
        if (bottom < old_y)
        {
            player->y = bottom + 0x100;
            return;
        }
    }
    if (g_player_displacement_x == 0 && g_player_displacement_z == 0)
    {
        player->x = x;
        player->z = back;
    }
    if (!(left < old_x) && g_player_displacement_x > 0)
        player->x = left;
    if (!(old_x < right) && g_player_displacement_x < 0)
        player->x = right;
    if (!(back < old_z) && g_player_displacement_z > 0)
        player->z = back;
    if (!(old_z < front) && g_player_displacement_z < 0)
        player->z = front;
}

