static const void *resolve_psx_address(uint32 address)
{
    sint32 overbins_size;
    const uint8 *overbins = (const uint8 *)overbins_data(&overbins_size);
    if (address >= 0x80010000u && (sint32)(address - 0x80010000u) < overbins_size)
        return overbins + (sint32)(address - 0x80010000u);
    if (address < 0x80010000u)
        return 0;
    return original_tables_address(address);
}

static uint32 read_executable_u32(uint32 address)
{
    const uint8 *p = (const uint8 *)resolve_executable_address(address);
    if (!p)
        return 0;
    return (uint32)p[0] | (uint32)p[1] << 8 | (uint32)p[2] << 16 | (uint32)p[3] << 24;
}

const void *player_assets_executable_pointer(uint32 address)
{
    return resolve_psx_address(read_executable_u32(address));
}

const void *player_assets_resolve_address(uint32 address)
{
    return resolve_psx_address(address);
}

/* Host relocation helper, formerly game_loop.c:read_executable_pointer and
 * render.c:executable_pointer_text. No separate MIPS entry. Unlike the generic
 * player_assets_executable_pointer, these callers require a valid source slot. */
const char *player_assets_executable_text_pointer(uint32 address)
{
    const uint8 *slot = (const uint8 *)player_assets_executable_address(address);
    uint32 target = (uint32)slot[0] | ((uint32)slot[1] << 8) | ((uint32)slot[2] << 16) | ((uint32)slot[3] << 24);
    return (const char *)player_assets_resolve_address(target);
}

