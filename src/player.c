/* The first word in each sequence is its mutable cursor. */
/* Original: FUN_80098A84. */
sint32 cheat_sequence_update(sint32 *sequence)
{
    sint32 *expected;
    if (g_pressed_buttons == 0)
        return 0;
    expected = sequence + sequence[0] + 1;
    if (g_pressed_buttons != expected[0])
    {
        sequence[0] = 0;
        return 0;
    }
    sequence[0]++;
    if (expected[1] != -1)
        return 0;
    sequence[0] = 0;
    return 1;
}

