{
    PLAYER *player = (PLAYER *)raw_player;
    INVENTORY_SLOT *slot = player->inventory;

    g_shared_scratch_value = 0;
    do
    {
        if (slot->type == (uint16)type)
            return slot;
        ++g_shared_scratch_value;
        ++slot;
    } while (g_shared_scratch_value < 16);
    return 0;
}

/* Original: FUN_80099B3C. */
void *player_inventory_add(sint32 type, sint32 count, void *raw_player)
{
    PLAYER *player = (PLAYER *)raw_player;
    INVENTORY_SLOT *slot = (INVENTORY_SLOT *)player_inventory_find(type, player);
    sint32 i;

    if (slot != 0)
    {
        /* The original sh precedes its unsigned 999 comparison: wrap first. */
        uint16 total = (uint16)(slot->count + (uint16)count);
        slot->count = total;
        if (total > 999)
            slot->count = 999;
        return slot;
    }

    slot = player->inventory;
    for (i = 0; i < 16; ++i, ++slot)
    {
        const ItemDefinition *definition;
        if (slot->count != 0)
            continue;
        slot->count = (uint16)count;
        slot->type = (uint16)type;
        definition = (const ItemDefinition *)item_definition_find(type);
        slot->frame_id = definition->frame;
        return slot;
    }
    return 0;
}

