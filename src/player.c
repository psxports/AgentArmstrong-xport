/* Original: FUN_80097128. */
COLLISION_RESULT *static_map_collision_resolve(sint32 old_x, sint32 old_y, sint32 old_z, sint32 new_x, sint32 new_y, sint32 new_z, sint32 width, sint32 height, sint32 depth)
{
    sint32 ox = div_256_trunc(old_x);
    sint32 oy = div_256_trunc(old_y);
    sint32 oz = g_map_depth_cells * 0xc0 - div_256_trunc(old_z);
    sint32 nx = div_256_trunc(new_x);
    sint32 ny = div_256_trunc(new_y);
    sint32 nz = g_map_depth_cells * 0xc0 - div_256_trunc(new_z);
    sint32 min_x = nx - width / 2;
    sint32 min_z = nz - depth / 2;
    sint32 floor_count = 0;
    sint32 cx, cz;
    sint32 current_x = ox, current_z = oz;
    sint32 walk_min_x = current_x - width / 2;
    sint32 walk_max_x = current_x + width / 2;
    sint32 walk_min_z = current_z - depth / 2;
    sint32 walk_max_z = current_z + depth / 2;
    sint32 x_blocked = 0, z_blocked = 0, alternate = 0;

    static_result.x = new_x;
    static_result.y = new_y;
    static_result.z = new_z;
    static_result.flags = 0;
    static_result.step = 0;

    /* 0x800972AC..0x800974E4: vertical collision over every cell touched by
     * the destination footprint. */
    {
        sint32 first_z = div_64_trunc(min_z);
        sint32 z_count = span_cell_count(min_z, depth);
        sint32 first_x = div_64_trunc(min_x);
        sint32 x_count = span_cell_count(min_x, width);
        sint32 zi, xi;
        for (zi = 0, cz = first_z; zi < z_count; ++zi, ++cz)
        {
            for (xi = 0, cx = first_x; xi < x_count; ++xi, ++cx)
            {
                MAP_MODEL_GROUP *group = cell_group(cx, cz);
                sint32 count = group_count(group);
                sint32 i;
                if (count != 0)
                    g_shared_scratch_value = count;
                for (i = 0; i < count; ++i)
                {
                    MAP_MODEL_INSTANCE *instance = (MAP_MODEL_INSTANCE *)(group + 1) + i;
                    sint32 id = instance->model_id;
                    OriginalModelDescriptor *model;
                    sint32 plane;
                    model = &g_model_descriptors[id];
                    if (model->collision != 1)
                    {
                        --g_shared_scratch_value;
                        continue;
                    }
                    if (ny < oy)
                    {
                        plane = instance->y - model->half_y + height + 1;
                        if (ny <= plane && plane <= oy)
                        {
                            static_result.flags |= 8;
                            static_result.y = plane * 0x100;
                            floor_rows[floor_count] = cz;
                            floor_columns[floor_count] = cx;
                            ++floor_count;
                            ny = plane;
                            break;
                        }
                    }
                    else
                    {
                        sint32 bottom = instance->y + model->half_y;
                        plane = bottom - 1;
                        if (!(ny + group->y_offset < plane || bottom + 7 < oy + group->y_offset))
                        {
                            static_result.flags |= 1;
                            static_result.y = plane * 0x100;
                            floor_rows[floor_count] = cz;
                            floor_columns[floor_count] = cx;
                            ++floor_count;
                            ny = plane;
                            break;
                        }
                    }
                    --g_shared_scratch_value;
                }
            }
        }
    }

    /* 0x800974E4..0x80097AC4: advance one model unit at a time, alternating
     * Z and X.  Only a footprint edge exactly crossing a 64-unit boundary
     * causes the newly entered row/column to be tested. */
    for (;;)
    {
        sint32 arrived = current_x == nx && current_z == nz;
        if (!x_blocked)
        {
            walk_min_x = current_x - width / 2;
            walk_max_x = current_x + width / 2;
        }
        if (!z_blocked)
        {
            walk_min_z = current_z - depth / 2;
            walk_max_z = current_z + depth / 2;
        }
        if (!z_blocked && nz != oz)
        {
            sint32 edge = nz < oz ? walk_min_z - 1 : walk_max_z;
            sint32 crossed = nz < oz ? ((edge & 0x3f) == 0x3f) : ((edge & 0x3f) == 0);
            if (crossed)
            {
                sint32 row = div_64_trunc(edge);
                sint32 first = div_64_trunc(walk_min_x);
                sint32 count_x = span_cell_count(walk_min_x, width);
                sint32 xi;
                for (xi = 0, cx = first; xi < count_x; ++xi, ++cx)
                {
                    MAP_MODEL_GROUP *group = cell_group(cx, row);
                    sint32 count = group_count(group), i;
                    if (count != 0)
                        g_shared_scratch_value = count;
                    for (i = 0; i < count; ++i)
                    {
                        MAP_MODEL_INSTANCE *instance = (MAP_MODEL_INSTANCE *)(group + 1) + i;
                        OriginalModelDescriptor *model = &g_model_descriptors[instance->model_id];
                        sint32 upper = instance->y - model->half_y;
                        sint32 lower = instance->y + model->half_y;
                        sint32 correction;
                        if (model->collision != 1 || upper < ny - height || ny < lower)
                        {
                            --g_shared_scratch_value;
                            continue;
                        }
                        correction = ny - lower;
                        if (correction < 0x16 && static_result.step < correction + 1)
                            static_result.step = correction + 1;
                        if (all_floor_rows_equal(floor_count, row))
                        {
                            static_result.y = div_256_trunc(new_y) * 0x100;
                            static_result.flags &= ~9;
                            ny = div_256_trunc(new_y);
                        }
                        z_blocked = 1;
                        static_result.flags |= 4;
                        static_result.z = (g_map_depth_cells * 0xc0 - current_z) * 0x100;
                        break;
                    }
                }
            }
        }
        if (!x_blocked && nx != ox)
        {
            sint32 edge = nx < ox ? walk_min_x - 1 : walk_max_x;
            sint32 crossed = nx < ox ? ((edge & 0x3f) == 0x3f) : ((edge & 0x3f) == 0);
            if (crossed)
            {
                sint32 column = div_64_trunc(edge);
                sint32 first = div_64_trunc(walk_min_z);
                sint32 count_z = span_cell_count(walk_min_z, depth);
                sint32 zi;
                for (zi = 0, cz = first; zi < count_z; ++zi, ++cz)
                {
                    MAP_MODEL_GROUP *group = cell_group(column, cz);
                    sint32 count = group_count(group), i;
                    if (count != 0)
                        g_shared_scratch_value = count;
                    for (i = 0; i < count; ++i)
                    {
                        MAP_MODEL_INSTANCE *instance = (MAP_MODEL_INSTANCE *)(group + 1) + i;
                        OriginalModelDescriptor *model = &g_model_descriptors[instance->model_id];
                        sint32 upper = instance->y - model->half_y;
                        sint32 lower = instance->y + model->half_y;
                        sint32 correction;
                        if (model->collision != 1 || upper < ny - height || ny < lower)
                        {
                            --g_shared_scratch_value;
                            continue;
                        }
                        correction = ny - lower;
                        if (correction < 0x16 && static_result.step < correction + 1)
                            static_result.step = correction + 1;
                        if (all_floor_columns_equal(floor_count, column))
                        {
                            static_result.y = div_256_trunc(new_y) * 0x100;
                            static_result.flags &= ~9;
                            ny = div_256_trunc(new_y);
                        }
                        x_blocked = 1;
                        static_result.flags |= 2;
                        static_result.x = current_x * 0x100;
                        break;
                    }
                }
            }
        }
        if (arrived)
            break;
        if (alternate)
        {
            if (current_x < nx)
                ++current_x;
            if (nx < current_x)
                --current_x;
        }
        else
        {
            if (current_z < nz)
                ++current_z;
            if (nz < current_z)
                --current_z;
        }
        alternate ^= 1;
    }
    return &static_result;
}

/* 0x80096EA0..0x80097128: moving/runtime collision lists built in the
 * eight-byte per-cell DAT_800D3E70 table. */
/* Original: FUN_80096EA0. */
COLLISION_RESULT *runtime_object_collision_resolve(sint32 old_x, sint32 old_y, sint32 old_z, sint32 new_x, sint32 new_y, sint32 new_z, sint32 width, sint32 height)
{
    sint32 min_x = new_x - width / 2;
    sint32 max_x = min_x + width;
    sint32 map_z = g_map_depth_cells * 0xc000 - new_z;
    sint32 cell_x = min_x < 0 ? (min_x + 0x3fff) >> 14 : min_x >> 14;
    sint32 cell_z = map_z < 0 ? (map_z + 0x3fff) >> 14 : map_z >> 14;
    sint32 start = (cell_x + cell_z * g_map_width_cells - 1 - g_map_width_cells);
    sint32 row = 0, visited = 0;
    uint8 *cell = g_dynamic_collision_cell_anchors + start * 8;
    (void)old_x;
    (void)old_y;
    dynamic_result.x = new_x;
    dynamic_result.y = new_y;
    dynamic_result.z = new_z;
    dynamic_result.flags = 0;
    g_dynamic_collision_hit = 0;
    if (g_dynamic_collision_cell_anchors == 0 || cell < g_dynamic_collision_cell_anchors)
        return &dynamic_result;
    while (cell <= g_dynamic_collision_cell_anchors + g_map_width_cells * g_map_depth_cells * 8 && visited < 9)
    {
        DYNAMIC_COLLISION_NODE *anchor = *(DYNAMIC_COLLISION_NODE **)cell;
        DYNAMIC_COLLISION_NODE *object = anchor ? anchor->next : 0;
        while (object != 0)
        {
            sint32 object_min_x = object->min_x;
            sint32 object_max_x = object->max_x;
            sint32 object_min_z = object->min_z;
            sint32 object_max_z = object->max_z;
            sint32 object_top = object->top_y;
            sint32 object_bottom = object->bottom_y;
            if (object_min_x <= max_x && min_x <= object_max_x && object_min_z <= new_z && new_z <= object_max_z && object_top <= new_y && new_y - height <= object_bottom)
            {
                sint32 plane = object_min_z;
                if (object->attribute == 0x25)
                    plane = object_max_z;
                dynamic_result.z = plane <= old_z ? object_max_z : object_min_z;
                dynamic_result.flags = 4;
                g_dynamic_collision_hit = 1;
                return &dynamic_result;
            }
            object = object->next;
        }
        ++row;
        cell += 8;
        if (row >= 3)
        {
            row = 0;
            cell += g_map_width_cells * 8 - 24;
        }
        ++visited;
    }
    return &dynamic_result;
}

/* 0x80097DB8..0x80098224: original collision dispatcher and flag merge. */
/* Original: FUN_80097DB8. */
uint32 player_collision_resolve(sint32 old_x, sint32 old_y, sint32 old_z, sint32 *x, sint32 *y, sint32 *z, sint32 *velocity_x, sint32 *velocity_y, sint32 width, sint32 height, sint32 depth)
{
    sint32 grounded = 0;
    sint32 prior_y = *y;
    COLLISION_RESULT *result;
    g_collision_flags = 0;
    {
        sint32 floor_y = map_floor_height_at(old_x, *y, old_z);
        if (floor_y < *y && *y < floor_y + 0x4000)
        {
            *y = floor_y;
            if (velocity_y)
                *velocity_y = 0;
            grounded = 1;
            g_collision_flags |= 1;
            g_current_collision_result->flags |= 1;
            prior_y = floor_y;
        }
        else
            g_collision_surface_resource = -2;
    }
    if (*z != old_z || *x != old_x)
    {
        result = runtime_object_collision_resolve(old_x, old_y, old_z, *x, *y, *z, (width / 2) << 8, height << 8);
        g_current_collision_result = result;
        *x = result->x;
        *z = result->z;
        g_collision_flags |= result->flags;
    }
    result = static_map_collision_resolve(old_x, old_y, old_z, *x, *y, *z, width, height, depth);
    g_current_collision_result = result;
    g_collision_flags |= result->flags;
    *x = result->x;
    *y = result->y;
    *z = result->z;
    if ((result->flags & 2) && velocity_x)
        *velocity_x = 0;
    if (result->flags & 8)
    {
        if ((result->flags & 6) == 0)
        {
            if (velocity_y)
                *velocity_y = 0x100;
        }
        else
        {
            result = static_map_collision_resolve(*x, *y + 0x100, *z, *x, *y, *z, width, height, depth);
            g_current_collision_result = result;
            *x = result->x;
            *y = result->y;
            *z = result->z;
            if ((result->flags & 8) == 0)
            {
                g_collision_flags &= ~8;
                *y = prior_y;
            }
        }
    }
    if (result->step != 0 && ((result->flags & 1) || (g_collision_flags & 1)))
    {
        *y -= result->step * 0x100;
        if (velocity_y)
            *velocity_y = 0;
        return 0;
    }
    if (result->flags & 1)
    {
        if ((result->flags & 6) == 0)
        {
            if (velocity_y)
                *velocity_y = 0x100;
            return 1;
        }
        result = static_map_collision_resolve(*x, *y, *z, *x, *y, *z, width, height, depth);
        g_current_collision_result = result;
        *x = result->x;
        *y = result->y;
        *z = result->z;
        if (!grounded && !(result->flags & 1))
        {
            g_collision_flags &= ~1;
            *y = prior_y;
        }
    }
    return (uint32)(g_collision_flags & 1);
}

/* Original: FUN_8009F594. */
void player_action_object_update(PLAYER_ACTION *object)
{
    sint32 old_x, old_y, old_z, y_offset;
    void (*callback)(void *);
    if (object->lifetime != 0)
    {
        --object->lifetime;
        if (object->lifetime == 0)
            object_destroy(object);
    }
    if (object->owner_effect != 0 && !world_object_is_visible(object->collision.x, object->collision.y, object->collision.z, 0x8000))
    {
        object->owner_effect->type = object->collision.object_type;
        object_destroy(object);
        return;
    }
    old_x = object->collision.x;
    old_y = object->collision.y;
    old_z = object->collision.z;
    if (!world_object_is_visible(old_x, old_y, old_z, 0x8000))
        return;
    object->collision.x += object->velocity_x;
    object->collision.y += object->velocity_y;
    object->collision.z += object->velocity_z;
    y_offset = g_scuba_stage_active ? player_bob_offset_update(0) : 0;
    object->velocity_y += object->gravity_y;
    if (player_collision_resolve(old_x, old_y, old_z, &object->collision.x, &object->collision.y, &object->collision.z, 0, 0, 0x20, 0x20, 5) != 0 && object->impact_callback != 0)
    {
        object->velocity_y = 0;
        object->impact_callback(object);
    }
    if (object->animation.start_address != 0)
        animation_update(&object->animation);
    if (object->field_dc != 0)
        --object->field_dc;
    if ((uint32)(object->lifetime - 1) < 0x13 && (g_frame_counter & 1) != 0)
        return;
    if (object->rotation >= 0x81)
        object->rotation_step = -12;
    if (object->rotation < -0x80)
        object->rotation_step = 12;
    object->rotation = (sint16)(object->rotation + object->rotation_step);
    if ((object->collision.receives_mask & 2) != 0)
        g_next_frame_object->light_delta = object->rotation;
    else
        g_next_frame_object->light_delta = 0;
    render_world_sprite(object->animation.frame, object->collision.x, object->collision.y + y_offset, object->collision.z, 0, 0x1000, 0x1000, (POLY_FT4 *)object->collision.prim, 0, 0, 0, (object->field_dc << 5) & 0x3ff);
    callback = object->tail_callback;
    if (callback != 0)
        callback(object);
}

