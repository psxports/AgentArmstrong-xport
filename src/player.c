/* Original: FUN_800943F0. */
static void player_particle_ring_update(PLAYER_PARTICLE_RING *object)
{
    const sint32 *trig = original_tables_mips_sine_table();
    sint32 angle;
    sint32 radius = -object->ring_index * 0x2000;
    sint32 map_span = g_map_depth_cells * 3 * 0x4000;
    sint32 point_x = 0, point_z = 0;
    sint32 phase;
    for (angle = 0; angle < 0x400; angle += 0x10)
    {
        sint32 cosine = div_256_trunc(trig[(angle + 0x100) & 0x3ff]);
        sint32 sine = div_256_trunc(trig[angle]);
        sint32 cosine_product = radius * cosine;
        sint32 sine_product = radius * sine;
        point_x = object->x + div_256_trunc(cosine_product - sine_product);
        point_z = div_256_trunc(cosine_product + sine_product);
    }
    /* 0x800943F0..0x800944BC computes these values but contains no store or
     * draw call; retain the original arithmetic while documenting that its
    * results are dead in the PAL executable. */
    (void)map_span;
    (void)point_x;
    (void)point_z;
    phase = object->phase + 1;
    object->phase = phase;
    if (phase == object->frames_per_ring)
    {
        sint32 ring = object->ring_index + 1;
        object->phase = 0;
        object->ring_index = ring;
        if (ring == object->ring_count)
            object_destroy(object);
    }
}

