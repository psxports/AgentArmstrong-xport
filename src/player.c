/* Direct decompilation of FUN_8009E29C. */
sint16 player_clamp_to_screen(uint32 buttons)
{
    PLAYER *player = (PLAYER *)g_player;
    sint16 mode;
    if (g_stage_index == 0x0b && g_hq_weapon_area_enabled == 0)
        return 0;
    mode = (buttons & 0x80) != 0;
    if ((g_pressed_buttons & 0x20) != 0)
    {
        INVENTORY_SLOT *selected = &player->inventory[g_selected_weapon_slot];
        if (selected->type == 0x2a || selected->type == 0x8c)
            mode = 2;
    }
    if (player->special_weapon_ticks != 0)
    {
        if (mode == 0 || (g_frame_counter & 0x1f) != 0)
            mode = 0;
        else
            sound_play_positional(0x1e, 0, 0x89, player->x, player->y, player->z);
    }
    return mode;
}

static void player_apply_map_x_limits(PLAYER *player)
{
    if (player->x < 0x2000 && player->velocity_x < 0)
    {
        player->x = 0x2000;
        player->velocity_x = 0;
    }
    if ((uint32)((g_map_width_subcells - 0x20) * 0x100) < (uint32)player->x && player->velocity_x > 0)
    {
        player->x = (g_map_width_subcells - 0x20) * 0x100;
        player->velocity_x = 0;
    }
}

static void player_apply_camera_and_room_limits(PLAYER *player)
{
    if (g_room_activation_pending != 0)
    {
        sint32 camera_depth = player->z - g_camera_world_z;
        sint32 projected_x = (player->x - g_camera_world_x) * 0x140 / camera_depth;
        if (0x87 < projected_x)
            player->x = camera_depth * 0x88 / 0x140 + g_camera_world_x;
        projected_x = (player->x - g_camera_world_x) * 0x140 / camera_depth;
        if (projected_x < -0x87)
            player->x = camera_depth * -0x88 / 0x140 + g_camera_world_x;
    }
    if (g_player_far_z_limit != -1 && player->z > g_player_far_z_limit - 0x2000)
        player->z = g_player_far_z_limit - 0x2000;
    if (g_player_near_z_limit != -1 && player->z < g_player_near_z_limit)
        player->z = g_player_near_z_limit;
}

static void draw_player_pose(PLAYER *player, sint32 process_mirror_toggle)
{
    ANIM *anim = player_anim(player);
    uint32 frame_id;
    sint32 mirror = player->facing_x;
    frame_id = (uint32)animation_update(anim);
    if (player->damage_cooldown != 0 && (g_frame_counter & 3) == 0)
        player->flash_clut_ticks = 1;
    if (process_mirror_toggle && (anim->flags & 2) != 0)
    {
        anim->reserved ^= 1;
        anim->flags &= (uint16)~2;
    }
    if (process_mirror_toggle && anim->reserved != 0)
        mirror = -mirror;
    if (process_mirror_toggle)
    {
        /* 8009CDF8..8009CE08: seed the next FrameObject's signed lighting /
         * depth adjustment before FUN_8008D108 consumes that record. */
        ((FrameObjectPartial *)g_next_frame_object)->light_delta = player->light_delta;
        player->light_delta = 0;
    }
    /* 0x8009CE08..0x8009CE58: the player uses the same world-sprite builder
     * as every other actor.  +0x44 is its persistent POLY_FT4 and +0xA8 its
     * 0x30-byte VRAM descriptor. */
    render_world_sprite(frame_id, player->x, player->y, player->z, mirror, g_default_model_scale, g_default_model_scale, &player->prim, 0, 2, &player->vram_descriptor, 0);
}

