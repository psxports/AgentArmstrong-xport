void pickup_icon_update(SPRITE *object)
{
    sint32 depth = object->collision.z - g_camera_world_z;
    sint32 horizontal = (sint32)(0u - (uint32)depth * 108u);
    sint32 scaled = object->field_c8;
    sint32 factor = (scaled < 0 ? scaled + 0xff : scaled) >> 8;
    sint32 product = (sint32)((uint32)factor * (uint32)depth);
    sint64 multiply = (sint64)product * (sint64)0x5c4de1b7;
    sint32 high = (sint32)(multiply >> 32);
    sint32 projected = (high >> 7) - (product >> 31);
    object->collision.x = g_camera_world_x + horizontal / 640;
    object->field_c8 = scaled + object->velocity_y;
    object->collision.y = g_camera_world_y + projected;
    if (object->scale_x == 0)
        object_destroy(object);
}

