/* Original: FUN_800A14E4. Direct translation of 0x800A14E4..0x800A16F4. */
sint32 mission_enemy_update_visibility(COLLISION *object, EFFECT *src, sint16 type, uint16 clut)
{
    VRAM_SPRITE *desc = object->frame_desc;
    sint32 visible = world_object_is_visible(object->x, object->y, object->z, 0x30000);
    if (!visible)
    {
        if (desc->region != 0)
            spr_vram_defer_release(desc);
        if (src == 0)
            goto remove_object;
        if (effect_is_visible(src) != 0)
            return 0;
    }
    else
    {
        if (!world_object_is_visible(object->x, object->y, object->z, 0x6000))
        {
            if (desc->region == 0)
                return 2;
            spr_vram_defer_release(desc);
            return 2;
        }
        if (desc->region != 0)
            return 1;
        g_vram_error_reporting_enabled = 0;
        if (type == 0x37)
            visible = spr_vram_allocate(desc, 0x46, 0x50, 1) != 0;
        else if (type == 0x6e)
            visible = spr_vram_allocate(desc, 0x5a, 0x30, 1) != 0;
        else if (type == 0x66 || type == 0x7e || type == 0x92 || type == 0x8e)
            visible = spr_vram_allocate(desc, 0x46, 0x5a, 1) != 0;
        else
            visible = spr_vram_allocate(desc, 0x40, 0x50, 1) != 0;
        g_vram_error_reporting_enabled = 1;
        if (visible)
        {
            desc->clut = clut;
            return 1;
        }
        if (src == 0)
            goto remove_object;
    }
    src->type = type;
remove_object:
    object_destroy(object);
    return 0;
}

