/* Direct translation of 0x8009D820..0x8009DC98. */
/* Original: FUN_8009D820. */
uint32 mission_objective_script_update(const MISSION_OBJECTIVE_SCRIPT *script)
{
    sint32 threshold = 32000;
    sint16 primary = 0, secondary = 0;
    uint32 primary_count = 0, secondary_count = 0;
    char text[32];
    uint32 command_idx;
    for (command_idx = 0; command_idx < script->count; ++command_idx)
    {
        const MISSION_OBJECTIVE_COMMAND *command = script->commands + command_idx;
        MISSION_OBJECTIVE_OP opcode = command->op;
        uint16 timer;
        if (opcode == MISSION_OBJECTIVE_PRIMARY)
        {
            primary = command->arg;
            XASSERT(!(primary < 0 || primary >= sizeof(g_mission.primary)));
            secondary = 0;
            primary_count++;
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_SECONDARY)
        {
            secondary = command->arg;
            XASSERT(!(secondary < 0 || secondary >= sizeof(g_mission.secondary)));
            primary = 0;
            secondary_count++;
            continue;
        }
        timer = 0;
        if (threshold != 32000)
        {
            XASSERT(!(g_mission.timer == 0));
            timer = g_mission.timer->elapsed_seconds;
        }
        if (threshold < timer)
        {
            if (g_mission.primary[primary] == 0 && primary != 0)
            {
                snprintf(text, sizeof(text), g_game_text.entries[79], primary);
                g_mission.primary[primary] = 2;
                mission_text_message_create(text);
                player_death_begin();
            }
            if (g_mission.secondary[secondary] == 0 && secondary != 0)
            {
                snprintf(text, sizeof(text), g_game_text.entries[80], secondary);
                g_mission.secondary[secondary] = 2;
                mission_text_message_create(text);
            }
        }
        if (opcode == MISSION_OBJECTIVE_TARGETS)
        {
            sint16 mode = command->arg;
            sint32 cur = 0, total = 0;
            XASSERT(!(mode != 0 && mode != 1));
            if ((primary != 0 && g_mission.primary[primary] != 0) || (secondary != 0 && g_mission.secondary[secondary] != 0))
                continue;
            if (mode == 0)
            {
                cur = g_mission.primary_targets_done;
                total = g_mission.primary_targets_total;
            }
            if (mode == 1)
            {
                cur = g_mission.secondary_targets_done;
                total = g_mission.secondary_targets_total;
            }
            timer = threshold == 32000 ? 0 : g_mission.timer->elapsed_seconds;
            if (cur == total && threshold >= timer)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_ACTION)
        {
            sint16 idx = command->arg;
            XASSERT(!(idx < 0 || idx >= 32));
            if (primary != 0)
                g_mission.primary_action_present = 1;
            timer = threshold == 32000 ? 0 : g_mission.timer->elapsed_seconds;
            if (g_mission.actions[idx] != 0 && threshold >= timer)
            {
                g_mission.primary[primary] = 1;
                g_mission.secondary[secondary] = 1;
            }
            else
            {
                g_mission.primary[primary] = 0;
                g_mission.secondary[secondary] = 0;
            }
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_END)
            return (primary_count << 16) + secondary_count;
        if (opcode == MISSION_OBJECTIVE_TIME_LIMIT)
        {
            threshold = command->arg;
            g_mission.timer_visible = 1;
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_NO_TIME_LIMIT)
        {
            threshold = 32000;
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_COUNT_NONZERO)
        {
            sint16 idx = command->arg;
            XASSERT(!(idx < 0 || idx >= 32));
            if ((primary == 0 || g_mission.primary[primary] == 0) && (secondary == 0 || g_mission.secondary[secondary] == 0) && g_mission.counts[idx] != 0)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_COUNT_ZERO)
        {
            sint16 idx = command->arg;
            XASSERT(!(idx < 0 || idx >= 32));
            if ((primary == 0 || g_mission.primary[primary] == 0) && (secondary == 0 || g_mission.secondary[secondary] == 0) && g_mission.counts[idx] == 0)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == MISSION_OBJECTIVE_COUNT_ABOVE)
        {
            sint16 idx = command->arg;
            XASSERT(!(idx < 0 || idx >= 32));
            sint16 val = command->threshold;
            if ((primary == 0 || g_mission.primary[primary] == 0) && (secondary == 0 || g_mission.secondary[secondary] == 0) && val < g_mission.counts[idx])
                mission_objective_complete(primary, secondary);
        }
    }
    fatal_error("MISSION SCRIPT END");
    abort();
}

