void mission_text_message_update(MISSION_TEXT_MESSAGE *object)
{
    if (object->steady == 0 || (g_frame_counter & 8) != 0)
        text_render(object->text, object->collision.x, object->collision.y);
    object->lifetime -= 1;
    if (object->lifetime == 0)
    {
        g_mission_message_slots[object->slot] = 0;
        object_destroy(object);
    }
}

/* Direct translation of 0x800A12DC..0x800A142C. */
/* Original: FUN_800A12DC. */
MISSION_TEXT_MESSAGE *mission_text_message_create(const char *text)
{
    MISSION_TEXT_MESSAGE *object = 0;
    sint16 slot;
    while ((object = (MISSION_TEXT_MESSAGE *)object_find_next_by_type(object, 0x5c)) != 0)
        if (object->source_text == text)
            return 0;
    object = (MISSION_TEXT_MESSAGE *)object_create(sizeof(*object), (FUNC_COLLISION_UPDATE)mission_text_message_update);
    object->text_width = (sint16)text_byte_length(text);
    object->collision.x = -((object->text_width * g_font_glyph_width) / 2);
    for (slot = 0; slot < 0x10 && g_mission_message_slots[slot] != 0; slot++)
    {
    }
    object->collision.y = slot * g_font_line_height - 0x4c;
    g_mission_message_slots[slot] = 1;
    object->slot = (uint8)slot;
    object->collision.object_type = 0x5c;
    strcpy(object->text, text);
    object->source_text = text;
    object->lifetime = 0xb4;
    object->steady = 1;
    return object;
}

/* 0x800ABC50..0x800ABD94.  At 0x800ABCF4 the original installs the
 * WATER/SCUBA.BIN callback at overlay address 0x800FEEB8. */
/* Original: FUN_800ABC50. */
void mission_complete_begin(void)
{
    PLAYER *player = g_player;
    MissionRecord *record;
    sint32 counts;
    if (player->health <= 0)
        return;
    g_mission_ending = 1;
    if (g_scuba_stage_active != 0)
    {
        if (player->update == (FUNC_COLLISION_UPDATE)scuba_mission_complete_player_update)
            return;
        player->update = (FUNC_COLLISION_UPDATE)scuba_mission_complete_player_update;
        goto begin_completion;
    }
    if (player->update == (FUNC_COLLISION_UPDATE)player_mission_complete_update || player->update == (FUNC_COLLISION_UPDATE)door_transition_player_update)
        return;
    player->update = (FUNC_COLLISION_UPDATE)player_mission_complete_update;
    if (g_stage_index != 4 && g_stage_index != 8)
        extraction_ladder_create(g_player_world_x, g_player_world_y, g_player_world_z + 0x100);
begin_completion:
    player->render_flags = 0;
    player->draw_mode = 0;
    player->death_delay = 0xb4;
    sound_voice_stop(&player->spatial_sound_handle);
    mission_text_message_create((const char *)player_assets_executable_pointer(0x8008280cu));
    record = mission_record_find_by_stage((sint16)g_stage_index);
    record->unlocked = 1;
    counts = mission_objective_counts();
    if (g_secondary_objective_count == 0 || g_secondary_objective_count <= (counts & 0xffff))
        record->unlocked = 2;
}

