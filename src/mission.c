    sint32 x = object->col.x, z = object->col.z, y;
    sint32 dx, dz, dir, muzzle_x, probe_y, player_y;
    sint32 random, target_x, target_y, target_z;

    if (!world_object_is_visible(x, object->col.y, z, 0x7e800))
    {
        if (object->desc.region != 0)
            spr_vram_defer_release(&object->desc);
        return;
    }
    if (object->desc.region == 0)
    {
        spr_vram_allocate(&object->desc, 100, 88, 1);
        object->desc.clut = sentry_clut;
    }
    dx = ((uint32)g_player_world.x - x);
    dz = ((uint32)g_player_world.z - z);
    dir = ((fixed_angle_from_vector(div_4096_trunc(dx), div_4096_trunc(dz)) + 0x40) & 0x3ff) >> 8;
    /* The mask limits the four frame selectors and muzzle offsets */
    muzzle_x = dir == 2 ? 0x4000 : (dir != 0 ? 0x2e00 : 0);
    render_world_spr(sentry_frames[dir], object->col.x, object->col.y, object->col.z, dir == 1, 0x11f4, 0x11f4, &object->col.prim, 0, 0, &object->desc, 0);
    object_embedded_hit_flash_apply(object);
    if ((g_render_state.frame & 0x3f) != 0)
        return;

    x = object->col.x;
    z = object->col.z;
    y = object->col.y;
    object->col.x = (uint32)x + (muzzle_x + (muzzle_x >> 1));
    probe_y = object->col.y;
    player_y = g_player_world.y;
    probe_y = (probe_y + 0x800u);
    object->col.y = probe_y;
    if (probe_y < player_y && swept_col_test(x, y, z, &object->col.x, &object->col.y, &object->col.z) != 0)
    {
        object->col.x = x;
        object->col.y = y;
        object->col.z = z;
        return;
    }
    object->col.x = x;
    object->col.y = y;
    object->col.z = z;
    random = random_range(0x4000);
    target_x = ((uint32)g_player_world.x + random);
    target_x = (target_x - 0x2000u);
    random = random_range(0x2000);
    target_y = g_player_world.y;
