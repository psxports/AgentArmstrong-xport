/* Direct translation of 0x8009D820..0x8009DC98. */
/* Original: FUN_8009D820. */
sint32 mission_objective_script_update(sint32 script_address)
{
    const sint16 *script = (const sint16 *)(intptr)script_address;
    sint32 threshold = 32000;
    sint16 primary = 0, secondary = 0;
    sint32 primary_count = 0, secondary_count = 0;
    char text[32];
    for (;;)
    {
        sint16 opcode = *script++;
        uint16 timer;
        if (opcode == -2)
        {
            primary = *script++;
            secondary = 0;
            primary_count++;
            continue;
        }
        if (opcode == -3)
        {
            secondary = *script++;
            primary = 0;
            secondary_count++;
            continue;
        }
        timer = mission_timer_value(threshold);
        if (threshold < (sint32)timer)
        {
            if (g_primary_objective_states[primary] == 0 && primary != 0)
            {
                sprintf(text, (const char *)player_assets_executable_pointer(0x8008277cu), primary);
                g_primary_objective_states[primary] = 2;
                mission_text_message_create(text);
                player_death_begin();
            }
            if (g_secondary_objective_states[secondary] == 0 && secondary != 0)
            {
                sprintf(text, (const char *)player_assets_executable_pointer(0x80082780u), secondary);
                g_secondary_objective_states[secondary] = 2;
                mission_text_message_create(text);
            }
        }
        if (opcode == -4)
        {
            sint16 mode = *script++;
            sint32 current = 0, total = 0;
            if ((primary != 0 && g_primary_objective_states[primary] != 0) || (secondary != 0 && g_secondary_objective_states[secondary] != 0))
                continue;
            if (mode == 0)
            {
                current = g_primary_target_current_count;
                total = g_primary_target_total_count;
            }
            if (mode == 1)
            {
                current = g_secondary_target_current_count;
                total = g_secondary_target_total_count;
            }
            timer = mission_timer_value(threshold);
            if (current == total && threshold >= (sint32)timer)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == -5)
        {
            sint16 index = *script++;
            if (primary != 0)
                g_primary_action_objective_present = 1;
            timer = mission_timer_value(threshold);
            if (g_action_trigger_states[index] != 0 && threshold >= (sint32)timer)
            {
                g_primary_objective_states[primary] = 1;
                g_secondary_objective_states[secondary] = 1;
            }
            else
            {
                g_primary_objective_states[primary] = 0;
                g_secondary_objective_states[secondary] = 0;
            }
            continue;
        }
        if (opcode == -6)
            return primary_count * 0x10000 + secondary_count;
        if (opcode == -7)
        {
            threshold = *script++;
            g_mission_timer_visible = 1;
            continue;
        }
        if (opcode == -8)
        {
            threshold = 32000;
            continue;
        }
        if (opcode == -10)
        {
            sint16 index = *script++;
            if ((primary == 0 || g_primary_objective_states[primary] == 0) && (secondary == 0 || g_secondary_objective_states[secondary] == 0) && g_objective_counts[index] != 0)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == -12)
        {
            sint16 index = *script++;
            if ((primary == 0 || g_primary_objective_states[primary] == 0) && (secondary == 0 || g_secondary_objective_states[secondary] == 0) && g_objective_counts[index] == 0)
                mission_objective_complete(primary, secondary);
            continue;
        }
        if (opcode == -13)
        {
            sint16 index = *script++;
            sint16 value = *script++;
            if ((primary == 0 || g_primary_objective_states[primary] == 0) && (secondary == 0 || g_secondary_objective_states[secondary] == 0) && value < (sint32)g_objective_counts[index])
                mission_objective_complete(primary, secondary);
        }
    }
}

