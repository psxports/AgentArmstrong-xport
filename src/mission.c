void extraction_ladder_create(sint32 x, sint32 y, sint32 z)
{
    MISSION_EXTRACTION_LADDER *effect;
    sint32 handle;
    if (g_scuba_stage_active == 0 && object_find_next_by_type(0, 0x4c) == 0)
        return;
    effect = (MISSION_EXTRACTION_LADDER *)object_create(sizeof(*effect), (FUNC_COLLISION_UPDATE)extraction_ladder_update);
    effect->collision.object_type = 0x91;
    effect->velocity_limit = 0x500;
    effect->field_84 = 0x500;
    effect->collision.x = x;
    effect->collision.y = y;
    effect->collision.z = z;
    effect->horizontal_acceleration = 0x40;
    effect->horizontal_velocity = 0x500;
    effect->ladder_x = x;
    effect->collision.y = g_camera_world_y + div_trunc(mul_lo(-g_vertical_cull_extent, z - g_camera_world_z), 0x163);
    handle = sound_play_nonpositional(0x1d, 0, 0);
    effect->sound_handle = (sint16)handle;
}

/* Direct translation of 0x8009D784..0x8009D81C. */
/* Original: FUN_8009D784. */
sint32 mission_objective_counts(void)
{
    sint32 index, primary = 0, secondary = 0;
    for (index = 1; index <= g_primary_objective_count; index++)
        if (g_primary_objective_states[index] == 1)
            primary++;
    for (index = 1; index <= g_secondary_objective_count; index++)
        if (g_secondary_objective_states[index] == 1)
            secondary++;
    return primary * 0x10000 + secondary;
}

