/* 0x8009E4C4..0x8009EA90. */
/* Original: FUN_8009E4C4. */
void extraction_ladder_update(MISSION_EXTRACTION_LADDER *effect)
{
    PLAYER *player = g_player;
    sint32 original_y = effect->collision.y;
    sint32 trail_y = 0, trail_z = 0;
    sint32 delta_x, ot;

    if (effect->phase_counter == 0)
    {
        /* 8009E50C: LW gp+0xA0 = 0x800D3D28, the player's global Y.
         * This is deliberately not the camera Y at 0x800D3EB4. */
        sint32 limit = g_player_world_y - 0x3000;
        if (original_y < limit)
            effect->collision.y = original_y + 0x100;
        else
            effect->phase_counter = 1;
    }
    if (effect->phase_counter >= 0x47)
    {
        effect->collision.y -= 0x100;
        effect->collision.x += 0x200;
        if (effect->phase_counter == 0x47)
        {
            effect->horizontal_acceleration = 0x20;
            effect->horizontal_velocity = 0;
            effect->velocity_limit = 0x280;
        }
        if (effect->phase_counter >= 0x15f)
        {
            object_destroy(effect);
            return;
        }
    }
    if (effect->phase_counter != 0)
        ++effect->phase_counter;

    if (effect->ladder_x < effect->collision.x)
    {
        if (effect->horizontal_direction == 1)
        {
            effect->horizontal_direction = 0;
            effect->horizontal_acceleration -= 8;
            effect->velocity_limit -= 0xa0;
        }
        effect->horizontal_velocity += effect->horizontal_acceleration;
    }
    if (effect->collision.x < effect->ladder_x)
    {
        if (effect->horizontal_direction == 0)
        {
            effect->horizontal_direction = 1;
            effect->horizontal_acceleration -= 8;
            effect->velocity_limit -= 0xa0;
        }
        effect->horizontal_velocity -= effect->horizontal_acceleration;
    }
    if (effect->velocity_limit < 0)
        effect->velocity_limit = 0;
    if (effect->horizontal_acceleration < 0)
        effect->horizontal_acceleration = 0;
    if (effect->horizontal_velocity < -effect->velocity_limit)
        effect->horizontal_velocity = -effect->velocity_limit;
    if (effect->velocity_limit < effect->horizontal_velocity)
        effect->horizontal_velocity = effect->velocity_limit;
    effect->ladder_x += effect->horizontal_velocity;

    delta_x = effect->ladder_x - effect->collision.x;
    ot = 0x480 - div_trunc(g_render_row_world_z - effect->collision.z, 0x100);
    for (;;)
    {
        sint32 projected_y = g_camera_world_y + div_trunc(mul_lo(-g_vertical_cull_extent, effect->collision.z - g_camera_world_z), 0x163);
        sint32 sprite_y = effect->collision.y + trail_y;
        sint32 middle_y, rotation;
        if (sprite_y <= projected_y)
            break;
        middle_y = sprite_y - div_trunc(delta_x < 0 ? -delta_x : delta_x, 5);
        rotation = div_trunc(-(delta_x + div_trunc(delta_x, 8)), 0x100) & 0x3ff;
        render_world_sprite(0x800, effect->collision.x + delta_x, middle_y, effect->collision.z + trail_z, 0, 0x1000, 0x1000, 0, (sint16)ot, 2, 0, rotation);
        /* 8009E804 is the same gp+0xA0 player-Y load. */
        if (middle_y > g_player_world_y - 0x3000 && middle_y - 0x1000 <= g_player_world_y - 0x3000 && effect->player_captured != 0)
            player->x = effect->collision.x + delta_x;
        delta_x = div_trunc(delta_x, 2) + div_trunc(delta_x, 3);
        trail_y -= 0x1000;
        trail_z -= 0x100;
        ++ot;
    }

    if (player->y < effect->collision.y && player->velocity_y > 0)
    {
        if (effect->player_captured == 0)
        {
            effect->player_captured = 1;
            effect->horizontal_acceleration = 0x40;
            effect->horizontal_velocity = 0x280;
            effect->velocity_limit = 0x280;
            player->animation.flags = 1;
            player->animation.frame = 0x1f400 + effect->player_frame;
            effect->capture_delay = 0x28;
        }
    }
    if (effect->player_captured != 0)
    {
        player->animation.frame = 0x1f400 + effect->player_frame;
        player->animation.flags = 1;
        player->velocity_y = 0;
        player->y += effect->collision.y - original_y;
        if (effect->capture_delay == 0)
        {
            if ((g_frame_counter & 3) == 0)
                ++effect->player_frame;
            player->y -= 0x300;
        }
        else
            --effect->capture_delay;
        if (effect->player_frame >= 0x0c)
            effect->player_frame = 0;
        g_hq_world_map_active = 1;
    }
    {
        sint32 distance = div_trunc(g_camera_world_y - effect->collision.y, 0x100);
        sint32 volume;
        sint16 pair[2];
        if (distance < 0)
            distance = 0;
        volume = 0x80 - distance;
        if (volume < 0)
            volume = 0;
        pair[0] = pair[1] = (sint16)(volume << 7);
        sound_voice_spatial_volume_update(pair, effect->sound_handle);
    }
}

/* 0x8009E3B4..0x8009E4C0, Mission-0 (normal module) branch. */
