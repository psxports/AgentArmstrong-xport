void building_map_deform(sint32 world_x, sint32 world_z, sint32 width, sint32 rows, sint32 delta, sint32 upper, sint32 lower)
{
    sint32 cell_x = div_pow2_trunc(world_x, 14);
    sint32 cell_z = div_pow2_trunc(g_map_depth_cells * 3 * 0x4000 - world_z, 14);
    MAP_FLOOR_CELL *row = g_map_floor_cells + cell_z * g_map_width_cells + cell_x;
    sint32 row_index;

    for (row_index = 0; row_index < rows; row_index++, row += g_map_width_cells)
    {
        sint32 column;
        MAP_FLOOR_CELL *cell = row;
        for (column = width; column > 0; column--, cell++)
        {
            sint16 value = cell->height;
            if (value < upper - 0x10)
            {
                cell->height = (sint16)(value + delta);
                if (cell->height >= upper - 0x10 && column != width && column != 1)
                    cell->height = (sint16)((uint16)cell->height + random_range(0x20));
            }
            if (column == 1 && (cell + 1)->height < upper + 0x10)
                (cell + 1)->height = (sint16)((cell + 1)->height + delta);
            {
                MAP_MODEL_GROUP *group = (MAP_MODEL_GROUP *)((uint8 *)g_map_model_groups + (uint32)cell->group_index * sizeof(*group));
                sint32 original_count = group->active_count;
                sint32 total = original_count + (group->removed_count + original_count);
                sint32 index;
                MAP_MODEL_INSTANCE *instance = (MAP_MODEL_INSTANCE *)(group + 1);
                for (index = 0; index < total; index++, instance++)
                {
                    sint32 instance_y = instance->y;
                    sint32 top;
                    if (index >= original_count)
                        instance_y -= 0x1388;
                    top = instance_y + g_model_descriptors[instance->model_id].half_y;
                    if (top < upper && top > lower)
                    {
                        instance->local_x = (sint16)((random_range(2) + 0x1f) << 8);
                        instance->y = (sint16)(instance->y + delta);
                        instance_y += delta;
                        if (instance_y + g_model_descriptors[instance->model_id].half_y >= upper)
                            instance->y = 0x1770;
                    }
                }
            }
        }
    }
    if (g_scuba_stage_active == 0)
    {
        sint32 column;
        MAP_FLOOR_CELL *cell = row;
        for (column = width; column > 0; column--, cell++)
        {
            sint16 value = cell->height;
            if (value < upper - 0x10)
                cell->height = (sint16)(value + delta);
            if (column == 1 && (cell + 1)->height < upper + 0x10)
                (cell + 1)->height = (sint16)((cell + 1)->height + delta);
        }
    }
}

