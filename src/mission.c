/* 0x800ABC50..0x800ABD94.  At 0x800ABCF4 the original installs the
 * WATER/SCUBA.BIN callback at overlay address 0x800FEEB8. */
/* Original: FUN_800ABC50. */
void mission_complete_begin(void)
{
    PLAYER *player = g_player;
    HQ_MAP_NODE *rec;
    sint32 counts;
    if (player->health <= 0)
        return;
    g_mission.ending = 1;
    if (g_session.scuba_active != 0)
    {
        if (player->col.object.update == scuba_mission_complete_player_update)
            return;
        player->col.object.update = scuba_mission_complete_player_update;
        goto begin_completion;
    }
    if (player->col.object.update == player_mission_complete_update || player->col.object.update == door_transition_player_update)
        return;
    player->col.object.update = player_mission_complete_update;
    if (g_session.stage != 4 && g_session.stage != 8)
        extraction_ladder_create(g_player_world.x, g_player_world.y, g_player_world.z + 0x100);
begin_completion:
    player->col.receives_mask = 0;
    player->col.sends_mask = 0;
    player->death_delay = 0xb4;
    sound_voice_stop(&player->spatial_sound_handle);
    mission_text_message_create(g_game_text.entries[115]);
    rec = hq_world_map_node_find_by_stage(g_session.stage);
    rec->unlocked = 1;
    counts = mission_objective_counts();
    if (g_mission.secondary_count == 0 || g_mission.secondary_count <= (counts & 0xffff))
        rec->unlocked = 2;
    game_progress_save();
}

/* Original: FUN_800A4184. */
void building_map_deform(sint32 world_x, sint32 world_z, sint32 width, sint32 rows, sint32 delta, sint32 upper, sint32 lower)
{
    sint32 cell_x = div_pow2_trunc(world_x, 14);
    sint32 cell_z = div_pow2_trunc((g_map.depth * 0xc000u - world_z), 14);
    sint32 cell_idx = cell_z * g_map.width + cell_x;
    sint32 row_idx;

    if (width <= 0)
        return;
    const sint32 upper_minus_16 = upper - 0x10u;
    const sint32 upper_plus_16 = upper + 0x10u;
    for (row_idx = 0; row_idx < rows; ++row_idx)
    {
        sint32 column;
        MAP_FLOOR_CELL *cell;
        XASSERT(!(g_map.floor == 0 || cell_idx >= g_map.floor_count || width >= g_map.floor_count - cell_idx));
        cell = g_map.floor + cell_idx;
        for (column = width; column > 0; column--, cell++)
        {
            sint16 val = cell->height;
            if (val < upper_minus_16)
            {
                cell->height = (val + delta);
                if (cell->height >= upper_minus_16 && column != width && column != 1)
                    cell->height = (cell->height + random_range(0x20));
            }
            if (column == 1 && (cell + 1)->height < upper_plus_16)
            {
                (cell + 1)->height = ((cell + 1)->height + delta);
            }

            /* Deform the model group after the optional edge-cell update */
            {
                MAP_MODEL_GROUP *grp = cell->grp;
                sint32 original_count = grp->active_count;
                sint32 total = original_count + (grp->removed_count + original_count);
                sint32 idx;
                MAP_MODEL_INSTANCE *instance = (grp + 1);
                sint32 grp_idx = grp - g_map.grps;
                XASSERT(!(total > 0 && (grp_idx >= g_map.rec_capacity || total > g_map.rec_capacity - grp_idx - 1)));
                for (idx = 0; idx < total; idx++, instance++)
                {
                    sint32 top = instance->y;
                    if (idx >= original_count)
                        top -= 0x1388;
                    XASSERT((instance->model_id) < g_model_catalog.count);
                    MODEL_DESC *desc = &g_model_catalog.descs[instance->model_id];
                    top += desc->half_y;
                    if (top < upper && top > lower)
                    {
                        instance->local_x = ((random_range(2) + 0x1f) << 8);
                        instance->y = (instance->y + delta);
                        top = (uint32)top + delta;
                        if (top >= upper)
                            instance->y = 0x1770;
                    }
                }
            }
        }
        cell_idx += g_map.width;
    }
    if (g_session.scuba_active == 0)
    {
        sint32 column;
        MAP_FLOOR_CELL *cell;
        XASSERT(!(g_map.floor == 0 || cell_idx >= g_map.floor_count || width >= g_map.floor_count - cell_idx));
        cell = g_map.floor + cell_idx;
        for (column = width; column > 0; column--, cell++)
        {
            sint16 val = cell->height;
            if (val < upper_minus_16)
                cell->height = (val + delta);
            if (column == 1 && (cell + 1)->height < upper_plus_16)
                (cell + 1)->height = ((cell + 1)->height + delta);
        }
    }
}

/* Original: FUN_800A3F90. */
static void destructible_building_update(void *raw_object)
{
    BUILDING *object = (BUILDING *)raw_object;
    sint32 age = object->age;
    building_map_deform(object->map_x, object->map_z, object->cell_width, object->cell_rows, age < 100 ? 0 : 4, object->upper_height, object->lower_height);
    if (age >= 100)
    {
        if (object->sound_delay == 0)
        {
            sint32 channel;
            sint32 sound;
            sint32 prev = prev_destruction_sound_variant;
            object->sound_delay = (random_range(30) + 30);
            channel = -random_range(8);
            sound = random_range(3);
            if (prev == sound)
                sound++;
            sound &= 3;
            prev_destruction_sound_variant = sound;
            sound_play_nonpositional(sound + 0x6b, channel, 0x7f);
        }
        else
            --object->sound_delay;
    }
    ++object->age;
    if ((g_render_state.frame & 3) == 0)
    {
        SPRITE *effect = world_spr_create(object->col.x + (random_range(object->cell_width << 6) << 8), object->col.y, object->col.z + object->col.box_z, g_particle_animation);
        effect->scale_x = (random_range(0x800) + 0x2000);
        effect->velocity_y = -0x300;
    }
    if (object->age > object->lifetime)
    {
        object_destroy(object);
        sound_voice_stop(&object->sound_handle);
        --g_mission.counts[6];
        speech_random_request(4);
    }
}

