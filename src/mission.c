/* Direct translation of 0x800A0930..0x800A0BEC. */
/* Original: FUN_800A0930. */
void hud_bar_render(MISSION_HUD_BAR *hud, sint32 amount, sint32 unused, sint32 zero_width)
{
    RENDER_PACKET_ARENA *arena = g_gpu_packets;
    POLY_G4 *poly2 = &hud->fill;
    POLY_F4 *poly3 = &hud->border;
    sint32 maximum = hud->maximum;
    sint32 width = hud->width;
    sint32 visible_width = zero_width;
    if (maximum < amount)
        amount = maximum;
    if (amount != 0)
    {
        sint32 ratio = (maximum << 16) / amount;
        sint32 empty_width = (width << 16) / ratio;
        sint32 full_ratio, empty_ratio;
        if (empty_width == 0)
            empty_width = 1;
        full_ratio = (width << 16) / empty_width;
        empty_ratio = (width << 16) / (width - empty_width);
        poly2->p[0].rgbc.r = poly2->p[1].rgbc.r = poly2->p[2].rgbc.r = poly2->p[3].rgbc.r = (0xff0000 / empty_ratio);
        poly2->p[0].rgbc.g = poly2->p[1].rgbc.g = poly2->p[2].rgbc.g = poly2->p[3].rgbc.g = (0xff0000 / full_ratio);
        visible_width = empty_width;
    }
    poly2->p[0].xy.x = poly2->p[2].xy.x = hud->x;
    poly2->p[1].xy.x = poly2->p[3].xy.x = (hud->x + visible_width);
    poly2->p[0].xy.y = poly2->p[1].xy.y = hud->y;
    poly2->p[2].xy.y = poly2->p[3].xy.y = (hud->y + 6);
    if (amount != 0)
    {
        XASSERT(!(arena == 0 || arena->used > RENDER_PRIM_CAPACITY || sizeof(*poly2) > RENDER_PRIM_CAPACITY - arena->used));
        POLY_G4 *poly0 = (POLY_G4 *)(arena->data.bytes + arena->used);
        memcpy(poly0, poly2, sizeof(*poly2));
        /* The PAL OT applies DR_OFFSET(160,64) before these screen-space
         * packets.  Native AddPrim records that GPU state per packet. */

        AddPrim(g_cur_render_frame->ot, poly0);
        arena->used += sizeof(*poly2);
    }
    XASSERT(!(arena == 0 || arena->used > RENDER_PRIM_CAPACITY || sizeof(*poly3) > RENDER_PRIM_CAPACITY - arena->used));
    POLY_F4 *poly1 = (POLY_F4 *)(arena->data.bytes + arena->used);
    memcpy(poly1, poly3, sizeof(*poly3));

    AddPrim(g_cur_render_frame->ot, poly1);
    arena->used += sizeof(*poly3);
}

/* Exact 0x800A0C18..0x800A0FF0 target-indicator branch. */
static void draw_target_indicator(void)
{
    MODEL_NODE node;
    COLLISION *target = (COLLISION *)object_find_next_by_type(0, 4);
    FIXED_DDA_LINE line;
    sint32 rotation_x, rotation_y;
    sint32 target_depth = g_camera.world_z + 0x12c00;
    sint32 denominator = target_depth - g_camera.world_z;
    RENDER_PACKET_ARENA *arena = g_gpu_packets;
    DR_OFFSET *packet;
    sint16 offset[2];
    MATRIX identity;
    rotation_x = rotation_y = ((g_render_state.frame & 0x7f) << 5);
    if (target)
    {
        sint32 x, z, horizontal, y;
        fixed_dda_initialize(g_player_world.x, g_player_world.y, g_player_world.z, target->x, target->y, target->z, &line);
        x = div_2048_trunc(line.step.x);
        z = div_2048_trunc(line.step.z);
        rotation_y = fixed_angle_from_vector(x, z) << 2;
        x = line.step.x < 0 ? -line.step.x : line.step.x;
        z = line.step.z < 0 ? -line.step.z : line.step.z;
        horizontal = x < z ? z + x / 2 : x + z / 2;
        y = div_2048_trunc(line.step.y);
        horizontal = div_2048_trunc(horizontal);
        if (horizontal < 0)
            horizontal = -horizontal;
        rotation_x = (-fixed_angle_from_vector(y, horizontal) << 2) & 0xfff;
    }
    memset(&node, 0, sizeof(node));
    node.rotation_x = rotation_x;
    node.rotation_y = rotation_y;
    node.rotation_z = 0;
    node.translation_x = g_player_world.x - g_camera.world_x;
    node.translation_y = g_player_world.y - g_camera.world_y;
    node.translation_z = denominator;
    node.model_id = g_model_selections.target_indicator;
    g_model_draw.target_frame = 0;
    model_render_begin();
    g_model_draw.depth_bucket = 0;
    g_model_draw.world_z = target_depth;
    memset(&identity, 0, sizeof(identity));
    identity.m[0][0] = identity.m[1][1] = identity.m[2][2] = 0x1000;
    XASSERT(!(arena == 0 || arena->used > RENDER_PRIM_CAPACITY || sizeof(*packet) > RENDER_PRIM_CAPACITY - arena->used));
    packet = (DR_OFFSET *)(arena->data.bytes + arena->used);
    memset(packet, 0, sizeof(*packet));
    SetDrawOffset(packet, g_cur_render_frame->drawenv.ofs);
    AddPrim(g_cur_render_frame->ot + g_model_draw.depth_bucket, packet);
    arena->used += sizeof(*packet);
    model_render_node(&node, &identity);
    model_render_end();
    denominator = target_depth - g_camera.world_z;
    offset[0] = (g_cur_render_frame->drawenv.ofs[0] - 0x28 - (g_player_world.x - g_camera.world_x) * 0x140 / denominator);
    offset[1] = (g_cur_render_frame->drawenv.ofs[1] - (g_player_world.y - g_camera.world_y) * 0x163 / denominator + 0x94);
    XASSERT(!(arena->used > RENDER_PRIM_CAPACITY || sizeof(*packet) > RENDER_PRIM_CAPACITY - arena->used));
    packet = (DR_OFFSET *)(arena->data.bytes + arena->used);
    memset(packet, 0, sizeof(*packet));
    SetDrawOffset(packet, offset);
    AddPrim(g_cur_render_frame->ot + g_model_draw.depth_bucket, packet);
    arena->used += sizeof(*packet);
}

/* Mission-HUD path of 0x800A0BF0..0x800A1178. */
