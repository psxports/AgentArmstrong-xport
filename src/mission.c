/* Original: FUN_800A617C. Direct translation of 0x800A617C..0x800A62A8. */
static sint32 projectile_test_path(sint32 x0, sint32 y0, sint32 z0, sint32 x1, sint32 y1, sint32 z1, sint32 steps)
{
    PROJECTILE *probe = projectile_create(x0, y0, z0, x1, y1, z1);
    probe->probe_mode = 1;
    while (steps > 0)
    {
        if (x1 - 0x500 < probe->collision.x && probe->collision.x < x1 + 0x500 && y1 - 0x500 < probe->collision.y && probe->collision.y < y1 + 0x500 && z1 - 0x500 < probe->collision.z && probe->collision.z < z1 + 0x500)
            break;
        if (projectile_update(probe) != 0)
        {
            object_destroy(probe);
            return 1;
        }
        --steps;
    }
    object_destroy(probe);
    return 0;
}

