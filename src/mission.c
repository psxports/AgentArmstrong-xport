/* 0x8008A04C..0x8008A120.  Mission-unlock text shown after the completion
 * menu.  The saved word at gp+0x518 is DAT_800D41A0, not an input field. */
/* Original: FUN_8008A04C. */
void mission_unlock_text_show(sint32 stage)
{
    const char *text = (const char *)mission_text_pointer(0x80082640u, (sint16)stage);
    const char *caption = (const char *)mission_text_pointer(0x8008275cu, 0);
    sint16 offset = -0x50;
    sint16 extent = (sint16)((uint16)g_font_line_height * (uint16)text_line_break_count(text));
    uint32 saved_tick = g_frame_counter;
    for (;;)
    {
        frame_begin();
        offset = hq_scrolling_text_render(text, offset, extent, caption, 0);
        screen_overlay_draw();
        end_frame_submit(0);
        if ((g_pressed_buttons & 0x10) != 0 || xport_isquit())
            break;
    }
    g_player->menu_resume = 1;
    g_frame_counter = saved_tick;
}

