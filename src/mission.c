/* Original: FUN_800A640C. Direct translation of 0x800A640C..0x800A66D0. */
static sint32 projectile_update(PROJECTILE *object)
{
    sint32 old_x = object->collision.x;
    sint32 old_y = object->collision.y;
    sint32 old_z = object->collision.z;
    sint32 floor_y;
    sint16 collision;
    fixed_dda_advance(object->motion);
    if (object->wind_enabled != 0)
        object->motion[0] += g_effect_wind_x * 0x100;
    {
        sint32 value = object->motion[0];
        if (value < 0)
            value += 0xff;
        object->collision.x = value >> 8;
        value = object->motion[1];
        if (value < 0)
            value += 0xff;
        object->collision.y = value >> 8;
        value = object->motion[2];
        if (value < 0)
            value += 0xff;
        object->collision.z = value >> 8;
    }
    if (object->probe_mode == 0)
    {
        if (!world_object_is_visible(object->collision.x, object->collision.y, object->collision.z, 0xc800))
            object_destroy(object);
        animation_update(&object->animation);
        g_next_frame_object->force_light = 1;
        render_world_sprite((uint32)object->animation.frame, object->collision.x, object->collision.y, object->collision.z, 0, object->scale, object->scale, (POLY_FT4 *)object->collision.prim, 0, 0, 0, 0);
    }
    floor_y = map_floor_height_at(object->collision.x, object->collision.y, object->collision.z);
    collision = swept_collision_test(old_x, old_y, old_z, &object->collision.x, &object->collision.y, &object->collision.z);
    if (collision == 0 && object->collision.y <= floor_y)
    {
        FUNC_COLLISION_UPDATE callback = object->floor_callback;
        if (callback != 0)
            callback(object);
        return 0;
    }
    {
        FUNC_COLLISION_UPDATE callback = object->impact_callback;
        if (callback == 0)
        {
            if (object->probe_mode == 0)
            {
                SPRITE *impact;
                object_destroy(object);
                impact = world_sprite_create(object->collision.x, object->collision.y, object->collision.z, bullet_impact_animation);
                g_shared_result_pointer = impact;
                impact->scale_x = 0x1800;
                projectile_surface_impact_emit(object->collision.x, object->collision.y, object->collision.z);
            }
        }
        else
        {
            callback(object);
            object_destroy(object);
        }
    }
    return 1;
}

