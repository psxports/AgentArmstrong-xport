/* 0x8009E4C4..0x8009EA90. */
/* Original: FUN_8009E4C4. */
static void extraction_ladder_update(void *raw_effect)
{
    MISSION_EXTRACTION_LADDER *effect = (MISSION_EXTRACTION_LADDER *)raw_effect;
    PLAYER *player = g_player;
    sint32 original_y = effect->col.y;
    sint32 trail_y = 0, trail_z = 0;
    sint32 delta_x, ot;

    if (effect->phase_counter == 0)
    {
        /* 8009E50C: LW gp+0xA0 = 0x800D3D28, the player's global Y.
         * This is deliberately not the camera Y at 0x800D3EB4. */
        sint32 limit = g_player_world.y - 0x3000u;
        if (original_y < limit)
            effect->col.y = original_y + 0x100u;
        else
            effect->phase_counter = 1;
    }
    if (effect->phase_counter >= 0x47)
    {
        effect->col.y = effect->col.y - 0x100u;
        effect->col.x = effect->col.x + 0x200u;
        if (effect->phase_counter == 0x47)
        {
            effect->horizontal_acceleration = 0x20;
            effect->horizontal_velocity = 0;
            effect->velocity_limit = 0x280;
        }
        if (effect->phase_counter >= 0x15f)
        {
            object_destroy(effect);
            return;
        }
    }
    if (effect->phase_counter != 0)
        ++effect->phase_counter;

    if (effect->ladder_x < effect->col.x)
    {
        if (effect->horizontal_dir == 1)
        {
            effect->horizontal_dir = 0;
            effect->horizontal_acceleration = (effect->horizontal_acceleration - 8u);
            effect->velocity_limit = (effect->velocity_limit - 0xa0u);
        }
        effect->horizontal_velocity = ((uint32)effect->horizontal_velocity + effect->horizontal_acceleration);
    }
    if (effect->col.x < effect->ladder_x)
    {
        if (effect->horizontal_dir == 0)
        {
            effect->horizontal_dir = 1;
            effect->horizontal_acceleration = (effect->horizontal_acceleration - 8u);
            effect->velocity_limit = (effect->velocity_limit - 0xa0u);
        }
        effect->horizontal_velocity = ((uint32)effect->horizontal_velocity - effect->horizontal_acceleration);
    }
    if (effect->velocity_limit < 0)
        effect->velocity_limit = 0;
    if (effect->horizontal_acceleration < 0)
        effect->horizontal_acceleration = 0;
    if (effect->horizontal_velocity < -effect->velocity_limit)
        effect->horizontal_velocity = -effect->velocity_limit;
    if (effect->velocity_limit < effect->horizontal_velocity)
        effect->horizontal_velocity = effect->velocity_limit;
    effect->ladder_x = ((uint32)effect->ladder_x + effect->horizontal_velocity);

    delta_x = ((uint32)effect->ladder_x - effect->col.x);
    ot = 0x480 - div_trunc(((uint32)g_map_render.depth_anchor_z - effect->col.z), 0x100);
    for (;;)
    {
        sint32 proj_y = g_camera.world_y + (uint32)div_trunc(((-(uint32)g_map_render.vertical_extent) * ((uint32)effect->col.z - g_camera.world_z)), 355);
        sint32 spr_y = (uint32)effect->col.y + trail_y;
        sint32 middle_y, rotation;
        if (spr_y <= proj_y)
            break;
        middle_y = (spr_y - (uint32)div_trunc(abs_s32(delta_x), 5));
        rotation = div_trunc(-(delta_x + (uint32)div_trunc(delta_x, 8)), 0x100) & 0x3ff;
        render_world_spr(0x800, ((uint32)effect->col.x + delta_x), middle_y, ((uint32)effect->col.z + trail_z), 0, 0x1000, 0x1000, 0, ot, 2, 0, rotation);
        /* 8009E804 is the same gp+0xA0 player-Y load. */
        if (middle_y > (g_player_world.y - 0x3000) && (middle_y - 0x1000) < (g_player_world.y - 0x3000) && effect->player_captured != 0)
            player->col.x = (uint32)effect->col.x + delta_x;
        delta_x = div_trunc(delta_x, 2) + div_trunc(delta_x, 3);
        trail_y = (trail_y - 0x1000u);
        trail_z = (trail_z - 0x100u);
        ot = (ot + 1u);
    }

    if (player->col.y < effect->col.y && player->velocity_y > 0)
    {
        if (effect->player_captured == 0)
        {
            effect->player_captured = 1;
            effect->horizontal_acceleration = 0x40;
            effect->horizontal_velocity = 0x280;
            effect->velocity_limit = 0x280;
            player->animation.delay = 1;
            player->animation.frame = 0x1f400 + effect->player_frame;
            effect->capture_delay = 0x28;
        }
    }
    if (effect->player_captured != 0)
    {
        player->animation.frame = 0x1f400 + effect->player_frame;
        player->animation.delay = 1;
        player->velocity_y = 0;
        player->col.y = player->col.y + ((uint32)effect->col.y - original_y);
        if (effect->capture_delay == 0)
        {
            if ((g_render_state.frame & 3) == 0)
                ++effect->player_frame;
            player->col.y = player->col.y - 0x300u;
        }
        else
            --effect->capture_delay;
        if (effect->player_frame >= 0x0c)
            effect->player_frame = 0;
        g_camera.frozen = 1;
    }
    {
        sint32 distance = div_trunc(((uint32)g_camera.world_y - effect->col.y), 0x100);
        sint32 volume;
        SOUND_VOLUME_PAIR pair;
        if (distance < 0)
            distance = 0;
        volume = 0x80 - distance;
        if (volume < 0)
            volume = 0;
        pair.volume_left = pair.volume_right = (volume << 7);
        sound_voice_spatial_volume_update(&pair, effect->sound_handle);
    }
}

