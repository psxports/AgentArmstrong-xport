/* Exact resident helper 0x800AD8A8..0x800AD9DC.  The four selected hierarchy
 * nodes define a dynamic collision box around the visible airship body. */
/* Original: FUN_800AD8A8. */
void hierarchy_collision_box_update(COLLISION *object, MODEL_NODE *first_node, sint32 count)
{
    MODEL_NODE *node = first_node;
    sint32 n;
    sint32 min_x = node->world_x, min_y = node->world_y, min_z = node->world_z;
    sint32 max_x = min_x, max_y = min_y, max_z = min_z;
    for (n = 1; n < count; n++)
    {
        ++node;
        if (node->world_x < min_x)
            min_x = node->world_x;
        if (max_x < node->world_x)
            max_x = node->world_x;
        if (node->world_y < min_y)
            min_y = node->world_y;
        if (max_y < node->world_y)
            max_y = node->world_y;
        if (node->world_z < min_z)
            min_z = node->world_z;
        if (max_z < node->world_z)
            max_z = node->world_z;
    }
    collision_box_set(object, (max_x - min_x) / 0x100, (max_y - min_y) / 0x100, (max_z - min_z) / 0x100);
    object->box_y += (((max_y - min_y) / 0x100) >> 1) << 8;
}

