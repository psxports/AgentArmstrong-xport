/* Original: AIRSHIP_800FAF60. */
static void airship_update(AIRSHIP_ACTOR *actor)
{
    static const MATRIX identity = {{{4096, 0, 0}, {0, 4096, 0}, {0, 0, 4096}}, {0, 0, 0}};
    MODEL_NODE *root = &actor->nodes[0];
    MODEL_NODE *projectile_origin = &actor->nodes[5];
    MODEL_NODE *bomb_origin = &actor->nodes[7];
    MODEL_NODE *bomb_target = &actor->nodes[8];
    MODEL_NODE *aim_origin = &actor->nodes[9];
    sint32 target_y, angle, v, abs_v;

    if (actor->destruction_timer != 0)
    {
        if (actor->collision.x < g_camera_world_x)
            actor->target_velocity_x = 0x200;
        if (g_camera_world_x < actor->collision.x)
            actor->target_velocity_x = -0x200;
        actor->destruction_timer++;
        if (actor->destruction_timer == 0xdc)
            g_airship_destruction_complete = 1;
    }
    if (actor->collision.x < actor->min_x)
    {
        actor->target_velocity_x = 0x300;
        actor->target_yaw = 0x400;
    }
    if (actor->max_x < actor->collision.x)
    {
        actor->target_velocity_x = -0x300;
        actor->target_yaw = 0xbf8;
    }
    if (actor->velocity_x < actor->target_velocity_x)
        actor->velocity_x += 0x20;
    if (actor->target_velocity_x < actor->velocity_x)
        actor->velocity_x -= 0x20;
    actor->collision.x += actor->velocity_x;
    actor->nodes[1].rotation_z = (sint16)((g_frame_counter << 8) & 0xfff);
    if ((g_frame_counter & 0x3f) == 0)
        actor->aim_yaw_jitter = (sint16)(random_range(0x400) - 0x200);

    fixed_dda_initialize(aim_origin->world_x, aim_origin->world_y, aim_origin->world_z, g_player_world_x, g_player_world_y - 0x3000, g_player_world_z, actor->aim_line);
    angle = ((fixed_angle_from_vector(div_2048_trunc(actor->aim_line[3]), div_2048_trunc(actor->aim_line[5])) << 2) - root->rotation_y + actor->aim_yaw_jitter) & 0xfff;
    actor->nodes[9].rotation_y = angle_approach_wrapped((sint16)angle, 0x20, actor->nodes[9].rotation_y);
    actor->nodes[5].rotation_y = angle_approach_wrapped((sint16)((angle - actor->aim_yaw_jitter) & 0xfff), 0x40, actor->nodes[5].rotation_y);

    target_y = actor->base_y;
    actor->attack_timer--;
    if ((sint16)actor->attack_timer < 0x201)
    {
        if (actor->attack_timer == 0x200)
            actor->saved_target_velocity_x = actor->target_velocity_x;
        actor->target_velocity_x = 0;
        if ((sint16)actor->attack_timer < 0x1c4)
            target_y += 0xe400;
        if ((sint16)actor->attack_timer < 0x188)
        {
            if ((sint16)actor->attack_timer < 0x16a)
            {
                v = (0x320 - actor->health) / 12 + 0x30;
                if (v > 0x64)
                    v = 0x64;
                actor->nodes[2].rotation_y = (sint16)((actor->nodes[2].rotation_y + v) & 0xfff);
            }
            else
            {
                actor->nodes[2].rotation_y = angle_approach_wrapped((sint16)((actor->nodes[5].rotation_y + 0x400) & 0xfff), 0x40, actor->nodes[2].rotation_y);
            }
            if (actor->bomb_cooldown == 0)
            {
                PROJECTILE *projectile;
                actor->bomb_cooldown = 1;
                projectile = projectile_create(bomb_origin->world_x, bomb_origin->world_y - 0x100, bomb_origin->world_z, bomb_target->world_x, bomb_target->world_y - 0x100, bomb_target->world_z);
                projectile->motion[3] *= 3;
                projectile->motion[4] *= 3;
                projectile->motion[5] *= 3;
            }
            else
                actor->bomb_cooldown--;
        }
        if (actor->attack_timer == 0)
        {
            actor->target_velocity_x = actor->saved_target_velocity_x;
            actor->attack_timer = (uint16)(random_range(0x100) + 0x32c);
        }
    }

    if (actor->destruction_timer != 0)
    {
        sint32 projected = (-((actor->collision.z - g_camera_world_z) * 0x10) / 355) + g_camera_world_y;
        actor->collision.y += (actor->destruction_timer < 0x64 && projected < actor->collision.y) ? -0x200 : 0x200;
        if ((g_frame_counter & 3) == 0)
        {
            sint32 x;
            SPRITE *debris;
            if ((g_frame_counter & 0xf) == 0)
                sound_play_nonpositional(9, 0, 0x7f);
            x = actor->collision.x + (random_range(0xc8) - 0x64) * 0x100;
            debris = world_sprite_create(x, actor->collision.y + (random_range(0x50) - 0x28) * 0x100, actor->collision.z - 0x2000, (const sint32 *)win_code_module_address(0x800fb7d8));
            debris->scale_x = 0x1400;
            if (random_range(8) == 0)
                expl_flash_create(actor->collision.x, actor->collision.y, actor->collision.z - 0x2000);
        }
    }
    else
    {
        v = actor->collision.y - target_y;
        abs_v = v < 0 ? -v : v;
        if (abs_v > 0x400)
            abs_v = 0x400;
        actor->collision.y += target_y < actor->collision.y ? -abs_v : abs_v;
    }

    root->rotation_y = actor->destruction_timer == 0 ? angle_approach_wrapped(actor->target_yaw, 0x10, root->rotation_y) : (sint16)((uint16)root->rotation_y + 0x40);
    root->rotation_y &= 0xfff;
    v = actor->velocity_x;
    if (v < 0)
        v = -v;
    root->rotation_x = (sint16)(v / 21);
    root->translation_x = actor->collision.x - g_camera_world_x;
    root->translation_y = actor->collision.y + player_bob_offset_update(0) - g_camera_world_y;
    root->translation_z = actor->collision.z - g_camera_world_z;
    g_render_depth_bucket = 0x480 - (g_render_row_world_z - actor->collision.z) / 0x100;
    g_current_model_world_z = actor->collision.z;
    if (actor->hit_flash_timer != 0)
    {
        g_model_clut_override = g_hit_flash_clut;
        actor->hit_flash_timer--;
    }
    g_model_render_frame = g_current_render_frame;
    model_render_node(root, (MATRIX *)&identity);
    hierarchy_collision_box_update(actor, &actor->nodes[11], 4);
    g_model_clut_override = 0;

    if ((sint16)actor->attack_timer >= 0x201 && (g_frame_counter & 0x7f) == 0 && actor->destruction_timer == 0)
    {
        PROJECTILE *projectile = projectile_create(projectile_origin->world_x, projectile_origin->world_y, projectile_origin->world_z, g_player_world_x, g_player_world_y - 0x2000, g_player_world_z);
        projectile->damage = 0x80;
        projectile->floor_callback = (FUNC_COLLISION_UPDATE)explosive_projectile_trail_update;
        projectile->impact_callback = (FUNC_COLLISION_UPDATE)explosive_projectile_impact;
        projectile->collision.object_type = 0;
        projectile->collision.receives_mask |= 4;
        projectile->motion[3] *= 2;
        projectile->motion[4] *= 2;
        projectile->motion[5] *= 2;
        sound_play_positional(10, 0, 0x96, actor->collision.x, actor->collision.y, actor->collision.z);
        speech_random_request(10);
    }
    hud_bar_render(g_boss_health_bar, actor->health, 0, 0);
}

/* Original: AIRSHIP_800FB6C8. */
static void airship_damage(AIRSHIP_ACTOR *actor, void *source)
{
    if (object_damage_apply(actor, source))
    {
        speech_random_request(10);
        expl_flash_create(actor->collision.x, actor->collision.y, actor->collision.z);
        actor->destruction_timer = 1;
        actor->collision.receives_mask = 0;
    }
}

/* Original: AIRSHIP_800FADD4. */
void airship_create(EFFECT *effect)
{
    AIRSHIP_ACTOR *actor = (AIRSHIP_ACTOR *)runtime_heap_allocate(sizeof(*actor));
    const sint16 *models = (const sint16 *)win_code_module_address(0x800fb73c);
    sint32 n;
    effect->type = 0;
    actor->collision.update = (FUNC_COLLISION_UPDATE)airship_update;
    linked_list_append(g_object_list, actor);
    actor->collision.object_type = 0x81;
    for (n = 0; n < 15; n++)
    {
        MODEL_NODE *node = &actor->nodes[n];
        actor->node_table[n] = node;
        node->model_id = models[n] == -1 ? 0 : models[n];
        node->render_flags = 0x3f;
    }
    actor->nodes[0].scale = 0x1000;
    model_initialize_pose(win_code_module_address(0x800fb75c), actor->node_table, 1);
    actor->collision.x = effect->x;
    actor->collision.y = effect->y - 0x4000;
    actor->collision.z = effect->z - 0x3000;
    actor->collision.callback_18 = (FUNC_COLLISION_CALLBACK)airship_damage;
    actor->health = 0x320;
    actor->collision.receives_mask = 1;
    actor->base_y = actor->collision.y;
    actor->min_x = actor->collision.x - 0xc800;
    actor->max_x = actor->collision.x + 0xc800;
    actor->target_velocity_x = 0x300;
    actor->target_yaw = 0x400;
    actor->attack_timer = 0x52c;
    hud_bar_initialize(g_boss_health_bar, -0x28, -0x60, 0x50, 0x320);
}

