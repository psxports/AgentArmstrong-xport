/* Original: FUN_800A4EA8. */
static void jetpack_enemy_update(void *raw_object)
{
    AIRSHIP_DRONE *object = (AIRSHIP_DRONE *)raw_object;
    sint32 tx, ty, tz, frame = 0x1540a, scale, flare_scale;
    sint16 depth;
    EFFECT *waypoint;
    const SOUND_VOLUME_PAIR *sound;
    if (!world_object_is_visible(object->col.x, object->col.y, object->col.z, 0x20000))
    {
        if (object->vram_desc.region != 0)
            spr_vram_defer_release(&object->vram_desc);
        object->owner_effect->type = 0x47;
        sound_voice_stop(&object->sound_handle);
        object_destroy(object);
        return;
    }
    if (object->vram_desc.region == 0)
    {
        g_vram_error_reporting_enabled = 0;
        if (!spr_vram_allocate(&object->vram_desc, 0x40, 0x4c, 1))
        {
            object->owner_effect->type = 0x47;
            object_destroy(object);
            sound_voice_stop(&object->sound_handle);
            g_vram_error_reporting_enabled = 1;
            return;
        }
        /* 800A4F84 LHU reads 800D7682, the mutable palette-table element
         * 800D75D8 + 2*(15400 >> 10), populated by 8008CDE0..8008CDEC. */
        g_vram_error_reporting_enabled = 1;
        object->vram_desc.clut = g_spr_pal.cluts[0x15400u >> 10];
    }
    animation_update(&object->animation);
    object->col.x += object->velocity_x;
    object->col.y += object->velocity_y;
    object->col.z += object->velocity_z;
    if (object->sound_handle == -1)
    {
        if (object->animation.next == 0)
            object->sound_handle = sound_play_positional(0x2b, 0, 0x40, object->col.x, object->col.y, object->col.z);
    }
    else
    {
        sound = sound_spatial_volume_calculate(0x40, object->col.x, object->col.y, object->col.z);
        if (sound)
            sound_voice_spatial_volume_update(sound, object->sound_handle);
        else
            sound_voice_stop(&object->sound_handle);
    }
    if (object->animation.next != 0)
    {
        animation_update(&object->animation);
        frame = object->animation.frame;
        if (frame == 0x15405)
            object->velocity_y = -0x300;
    }
    else
    {
        if ((g_render_state.frame & 0x3f) == 0)
        {
            SPRITE *p = world_spr_create(object->col.x, object->col.y, object->col.z, parachute_bomb_animation);
            p->velocity_y = 0x200;
            p->col_callback = parachute_bomb_explode;
            p->frame_callback = parachute_bomb_update;
            p->col.receives_mask = 0;
            p->acceleration_y = 0;
            p->behavior.parachute_step = 2;
            p->velocity_x = g_player_world.x < object->col.x ? -0x80 : 0x80;
            p->velocity_z = g_player_world.z < object->col.z ? -0x80 : 0x80;
        }
        waypoint = object->route[object->route_idx];
        if (!waypoint)
            fatal_error_with_val("NO ROUTE %d", (sint16)object->owner_effect->vals[0]);
        tx = waypoint->x;
        ty = waypoint->y;
        tz = waypoint->z;
        if (tx - 0x3000 < object->col.x && object->col.x < tx + 0x3000 && ty - 0x3000 < object->col.y && object->col.y < ty + 0x3000 && tz - 0x3000 < object->col.z && object->col.z < tz + 0x3000)
        {
            object->route_idx = (object->route_idx + object->route_step);
            if (object->route_idx == object->route_count)
                object->route_idx = 0;
            if (object->route_idx < 0)
                object->route_idx = (object->route_count - 1);
            waypoint = object->route[object->route_idx];
            tx = waypoint->x;
            ty = waypoint->y;
            tz = waypoint->z;
        }
        if (object->col.x < tx && object->velocity_x < 0x300)
            object->velocity_x += 0x20;
        if (tx < object->col.x && object->velocity_x >= -0x2ff)
            object->velocity_x -= 0x20;
        if (object->col.y < ty && object->velocity_y < 0x200)
            object->velocity_y += 0x20;
        if (ty < object->col.y && object->velocity_y >= -0x1ff)
            object->velocity_y -= 0x20;
        if (object->col.z < tz && object->velocity_z < 0x300)
            object->velocity_z += 0x20;
        if (tz < object->col.z && object->velocity_z >= -0x2ff)
            object->velocity_z -= 0x20;
        object->yaw = angle_approach_wrapped((((object->col.x - tx) < 0 ? 0x28 : 0x3d8) * 4), 0x0c, (object->yaw * 4)) / 4;
        frame = 0x1540a;
        if (object->yaw < 0x3d8)
        {
            if (object->yaw >= 9)
                frame = 0x15409;
            if (object->yaw >= 0x11)
                frame = 0x15408;
            if (object->yaw >= 0x19)
                frame = 0x15407;
            if (object->yaw >= 0x21)
                frame = 0x15406;
        }
        else
        {
            if (object->yaw < 0x3f8)
                frame = 0x1540b;
            if (object->yaw < 0x3f0)
                frame = 0x1540c;
            if (object->yaw < 0x3e8)
                frame = 0x1540d;
            if (object->yaw < 0x3e0)
                frame = 0x1540e;
        }
    }
    depth = object->animation.next ? 0 : 0x480 - (g_map_render.depth_anchor_z - object->col.z) / 0x100;
    if (depth >= 0x480)
        depth = 0x47f;
    if (g_map_render.depth_anchor_z < object->col.z)
        return;
    render_world_spr(frame, object->col.x, object->col.y, object->col.z, 0, g_default_spr_scale, g_default_spr_scale, 0, depth, 0, &object->vram_desc, object->yaw);
    object_hit_flash_apply(object);
    flare_scale = 0x1000 - object->velocity_y * 2;
    scale = flare_scale / 2;
    if (object->animation.next != 0 && object->animation.flags != 1)
        return;
    if ((g_render_state.frame & 2) != 0)
        scale = flare_scale;
    POLY_FT4 *poly = g_next_transient_prim;
    XASSERT(!(g_next_transient_prim >= g_transient_prims + TRANSIENT_PRIM_LIMIT));
    SetPolyFT4(poly);
    SetSemiTrans(poly, 1);
    g_next_frame_object->light_delta = (-0x30 - (object->velocity_y >> 4));
    g_next_frame_object->force_light = 1;
    render_world_spr(0x27400, object->col.x - object->velocity_x * 2, object->col.y - 0x1800, object->col.z + 0x800, 0, scale, scale, poly, depth + 1, 0, 0, (g_render_state.frame * 8) & 0x3ff);
    ++g_next_transient_prim;
}

/* Original: FUN_800A4CD4. */
void jetpack_enemy_create(EFFECT *effect)
{
    AIRSHIP_DRONE *object = (AIRSHIP_DRONE *)runtime_heap_allocate(sizeof(*object));
    object->col.object.update = jetpack_enemy_update;
    linked_list_append(&g_object_list, object);
    object->col.x = effect->x;
    object->col.y = effect->y + 0x2000;
    object->col.z = effect->z;
    object->col.receives_mask = 0x81;
    object->col.hit_callback_kind = COLLISION_CALLBACK_NOTIFY;
    object->col.hit_callback = jetpack_enemy_damage;
    object->col.hit.health = 10;
    object->col.frame_desc = &object->vram_desc;
    col_box_set(object, 0x40, 0x40, 0x10);
    object->owner_effect = effect;
    effect->type = 0;
    object->route_count = route_waypoints_collect(effect->vals[0], -1, object->route, sizeof(object->route) / sizeof(object->route[0]));
    object->route_step = 1;
    animation_start(&object->animation, jetpack_animation);
    object->animation.owner = object;
    object->velocity_y = 0;
    object->sound_handle = -1;
}
