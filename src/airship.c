/* Exact 0x8009FEB0..0x8009FFCC: shift cell-model vertices whose Y lies in
 * the moving lift slab. */
/* Original: FUN_8009FEB0. */
void lift_deform_map_models(sint32 x, sint32 y, sint32 z, sint32 width, sint32 height, sint32 depth, sint32 delta)
{
    MAP_FLOOR_CELL *row = map_floor_cell_at(x, z);
    sint32 min_y = y < 0 ? (y + 0xff) >> 8 : y >> 8;
    sint32 r, c, n;
    MAP_MODEL_GROUP *groups = g_map_model_groups;
    for (r = 0; r < depth; r++, row += g_map_width_cells)
    {
        MAP_FLOOR_CELL *cell = row;
        for (c = 0; c < width; c++, cell++)
        {
            MAP_MODEL_GROUP *group = (MAP_MODEL_GROUP *)((uint8 *)groups + (uint32)cell->group_index * sizeof(*group));
            MAP_MODEL_INSTANCE *instance = (MAP_MODEL_INSTANCE *)(group + 1);
            n = group > groups ? group->active_count : 0;
            for (; n > 0; n--, instance++)
            {
                if (instance->y >= min_y && instance->y < min_y + height)
                    instance->y = (sint16)(instance->y + delta);
            }
        }
    }
}

/* Original: FUN_800A0128. */
static void lift_update(AIRSHIP_LIFT *lift)
{
    PLAYER *player = (PLAYER *)g_player;
    EFFECT *source = lift->waypoints[0];
    void *sound;
    sint32 shifted_x, shifted_z, target_y;
    sint16 gate;
    if (player->preserve_checkpoint != 0 && player->checkpoint == lift && player->update == player_checkpoint_recovery_update)
        return;
    shifted_z = lift->collision.z + 0x2000;
    lift->collision.x -= 0x2000;
    shifted_x = lift->collision.x;
    lift->collision.z = shifted_z;
    if (g_player_world_x + 0x1300 >= shifted_x && g_player_world_x - 0x1300 < shifted_x + (lift->cell_width << 14) && shifted_z >= g_player_world_z - 0x400 && shifted_z - (lift->cell_depth << 14) < g_player_world_z + 0x400 && g_player_world_y > lift->collision.y - 0x800 && g_player_world_y < lift->collision.y + (lift->cell_height << 8) && player->grounded != 0)
    {
        player->checkpoint = lift;
        player->preserve_checkpoint = 1;
    }
    lift->collision.x += 0x2000;
    lift->collision.z -= 0x2000;
    gate = source->values[6];
    if (gate != 0)
    {
        uint8 state = g_trigger_states[(uint16)gate];
        if (lift->collision.object_type != 0x96)
            lift->enabled = state;
        else if (lift->previous_gate_state != state)
        {
            lift->previous_gate_state = state;
            lift->enabled = 1;
        }
    }
    sound = sound_spatial_volume_calculate(0x40, lift->collision.x, lift->collision.y, lift->collision.z);
    if (lift->enabled == 0 && lift->wait_timer != 0x270f)
    {
        lift->wait_timer = 1;
        sound = 0;
    }
    if (lift->sound_disabled == 0)
    {
        if (lift->sound_handle == -1)
        {
            if (sound)
                lift->sound_handle = (sint16)sound_play_positional(0x16, 0, 0x40, g_player_world_x, g_player_world_y, g_player_world_z);
        }
        else if (!sound)
        {
            sound_voice_stop(&lift->sound_handle);
            lift->sound_handle = -1;
        }
        else
            sound_voice_spatial_volume_update(sound, lift->sound_handle);
    }
    if (lift->wait_timer == 0 && lift->enabled != 0)
    {
        lift_deform_map_models(lift->collision.x, lift->collision.y, lift->collision.z, lift->cell_width, lift->cell_height, lift->cell_depth, lift->delta_y / 0x100);
        lift->collision.y += lift->delta_y;
        target_y = lift->waypoints[lift->waypoint_index]->y + 0x1000;
        if (lift->collision.y == target_y)
        {
            lift->waypoint_index = (sint16)(lift->waypoint_index + lift->waypoint_step);
            if (lift->waypoint_index == lift->waypoint_count - 1)
                lift->waypoint_step = -1;
            if (lift->waypoint_index == 0)
                lift->waypoint_step = 1;
            target_y = lift->waypoints[lift->waypoint_index]->y;
            lift->delta_y = lift->collision.y >= target_y ? -0x200 : 0x200;
            lift->wait_timer = 0x18;
            if (lift->collision.object_type == 0x96)
                lift->delta_y *= 8;
            if (source->values[6] != 0)
            {
                if (lift->collision.object_type == 0x5a)
                {
                    lift->enabled = 0;
                    g_trigger_states[(uint16)source->values[6]] = 0;
                    lift->wait_timer = 0;
                }
                if (lift->collision.object_type == 0x96)
                    lift->enabled = 0;
            }
            if (++lift->completed_trips >= 0x80)
                lift->completed_trips = 0x7f;
            if (lift->completed_trips == 2 && lift->collision.object_type == 0x5b)
            {
                lift->wait_timer = 0x270f;
                sound_voice_stop(&lift->sound_handle);
                lift->sound_disabled = 1;
            }
        }
    }
    else if (lift->wait_timer != 0x270f)
        lift->wait_timer--;
}

/* Original: FUN_8009FFD0. */
void lift_create(EFFECT *effect)
{
    AIRSHIP_LIFT *lift = (AIRSHIP_LIFT *)runtime_heap_allocate(sizeof(*lift));
    EFFECT *scan = 0;
    sint16 route = effect->values[0], count = 1;
    lift->collision.update = (FUNC_COLLISION_UPDATE)lift_update;
    linked_list_append(g_object_list, lift);
    lift->collision.object_type = (sint16)effect->type;
    effect->type = 0;
    lift->collision.x = effect->x;
    lift->collision.y = effect->y + 0x1000;
    lift->collision.z = effect->z;
    lift->cell_width = effect->values[2];
    lift->cell_height = effect->values[3];
    lift->cell_depth = effect->values[4];
    lift->waypoints[0] = effect;
    for (;;)
    {
        scan = effect_find_next(0x1e, scan);
        if (!scan)
            break;
        if (scan->values[0] == route)
        {
            ++count;
            lift->waypoints[scan->values[1]] = scan;
        }
        ++scan;
    }
    lift->waypoint_step = 1;
    lift->sound_handle = -1;
    lift->waypoint_count = count;
    lift->enabled = 1;
    if (effect->values[6] != 0)
    {
        lift->enabled = g_trigger_states[(uint16)effect->values[6]];
        if (lift->enabled == 0)
            lift->previous_gate_state = 1;
    }
}
