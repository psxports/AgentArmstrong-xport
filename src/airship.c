/* Original: AIRSHIP:AIRSHIP_800FAF60. */
static void airship_update(void *raw_actor)
{
    AIRSHIP_ACTOR *actor = (AIRSHIP_ACTOR *)raw_actor;
    static const MATRIX identity = {{{4096, 0, 0}, {0, 4096, 0}, {0, 0, 4096}}, {0, 0, 0}};
    MODEL_NODE *root = &actor->nodes[0];
    MODEL_NODE *projectile_origin = &actor->nodes[5];
    MODEL_NODE *bomb_origin = &actor->nodes[7];
    MODEL_NODE *bomb_target = &actor->nodes[8];
    MODEL_NODE *aim_origin = &actor->nodes[9];
    sint32 target_y, angle, v, abs_v;

    if (actor->destruction_timer != 0)
    {
        if (actor->col.x < g_camera.world_x)
            actor->target_velocity_x = 0x200;
        if (g_camera.world_x < actor->col.x)
            actor->target_velocity_x = -0x200;
        actor->destruction_timer++;
        if (actor->destruction_timer == 0xdc)
            g_mission.counts[MISSION_COUNT_AIRSHIP_DONE] = 1;
    }
    if (actor->col.x < actor->min_x)
    {
        actor->target_velocity_x = 0x300;
        actor->target_yaw = 0x400;
    }
    if (actor->max_x < actor->col.x)
    {
        actor->target_velocity_x = -0x300;
        actor->target_yaw = 0xbf8;
    }
    if (actor->velocity_x < actor->target_velocity_x)
        actor->velocity_x += 0x20;
    if (actor->target_velocity_x < actor->velocity_x)
        actor->velocity_x -= 0x20;
    actor->col.x = (uint32)actor->col.x + actor->velocity_x;
    actor->nodes[1].rotation_z = (g_render_state.frame << 8) & 0xfff;
    if ((g_render_state.frame & 0x3f) == 0)
        actor->aim_yaw_jitter = random_range(0x400) - 0x200;

    fixed_dda_initialize(aim_origin->world_x, aim_origin->world_y, aim_origin->world_z, g_player_world.x, g_player_world.y - 0x3000u, g_player_world.z, &actor->aim_line);
    angle = ((fixed_angle_from_vector(div_2048_trunc(actor->aim_line.step.x), div_2048_trunc(actor->aim_line.step.z)) << 2) - root->rotation_y + actor->aim_yaw_jitter) & 0xfff;
    actor->nodes[9].rotation_y = angle_approach_wrapped(angle, 0x20, actor->nodes[9].rotation_y);
    actor->nodes[5].rotation_y = angle_approach_wrapped((angle - actor->aim_yaw_jitter) & 0xfff, 0x40, actor->nodes[5].rotation_y);

    target_y = actor->base_y;
    actor->attack_timer--;
    if (actor->attack_timer < 0x201)
    {
        if (actor->attack_timer == 0x200)
            actor->saved_target_velocity_x = actor->target_velocity_x;
        actor->target_velocity_x = 0;
        if (actor->attack_timer < 0x1c4)
            target_y = target_y + 0xe400u;
        if (actor->attack_timer < 0x188)
        {
            if (actor->attack_timer < 0x16a)
            {
                v = (0x320 - actor->col.hit.health) / 12 + 0x30;
                if (v > 0x64)
                    v = 0x64;
                actor->nodes[2].rotation_y = (actor->nodes[2].rotation_y + v) & 0xfff;
            }
            else
            {
                actor->nodes[2].rotation_y = angle_approach_wrapped((actor->nodes[5].rotation_y + 0x400) & 0xfff, 0x40, actor->nodes[2].rotation_y);
            }
            if (actor->bomb_cooldown == 0)
            {
                PROJECTILE *projectile;
                actor->bomb_cooldown = 1;
                projectile = projectile_create(bomb_origin->world_x, bomb_origin->world_y - 0x100u, bomb_origin->world_z, bomb_target->world_x, bomb_target->world_y - 0x100u, bomb_target->world_z);
                projectile->motion.step.x = projectile->motion.step.x * 3u;
                projectile->motion.step.y = projectile->motion.step.y * 3u;
                projectile->motion.step.z = projectile->motion.step.z * 3u;
            }
            else
                actor->bomb_cooldown--;
        }
        if (actor->attack_timer == 0)
        {
            actor->target_velocity_x = actor->saved_target_velocity_x;
            actor->attack_timer = random_range(0x100) + 0x32c;
        }
    }

    if (actor->destruction_timer != 0)
    {
        sint32 proj = -(((uint32)actor->col.z - g_camera.world_z) * 0x10u);
        proj = (uint32)(proj / 355) + g_camera.world_y;
        if (actor->destruction_timer < 0x64 && proj < actor->col.y)
            actor->col.y = actor->col.y - 0x200u;
        else
            actor->col.y = actor->col.y + 0x200u;
        if ((g_render_state.frame & 3) == 0)
        {
            sint32 x;
            SPRITE *debris;
            if ((g_render_state.frame & 0xf) == 0)
                sound_play_nonpositional(9, 0, 0x7f);
            x = actor->col.x + (random_range(0xc8) - 0x64u) * 0x100u;
            debris = world_spr_create(x, actor->col.y + (random_range(0x50) - 0x28u) * 0x100u, actor->col.z - 0x2000u, g_particle_animation);
            debris->scale_x = 0x1400;
            if (random_range(8) == 0)
                expl_flash_create(actor->col.x, actor->col.y, actor->col.z - 0x2000u);
        }
    }
    else
    {
        v = (uint32)actor->col.y - target_y;
        abs_v = v < 0 ? -(uint32)v : v;
        if (abs_v > 0x400)
            abs_v = 0x400;
        actor->col.y = actor->col.y + (target_y < actor->col.y ? -(uint32)abs_v : abs_v);
    }

    root->rotation_y = actor->destruction_timer == 0 ? angle_approach_wrapped(actor->target_yaw, 0x10, root->rotation_y) : root->rotation_y + 0x40;
    root->rotation_y &= 0xfff;
    v = actor->velocity_x;
    if (v < 0)
        v = -v;
    root->rotation_x = v / 21;
    root->translation_x = (uint32)actor->col.x - g_camera.world_x;
    v = player_bob_offset_update(0);
    root->translation_y = (uint32)actor->col.y + v - g_camera.world_y;
    root->translation_z = (uint32)actor->col.z - g_camera.world_z;
    v = (uint32)g_map_render.depth_anchor_z - actor->col.z;
    g_model_draw.depth_bucket = 0x480u - (v / 0x100);
    g_model_draw.world_z = actor->col.z;
    if (actor->col.flash_clut_ticks != 0)
    {
        g_model_draw.clut_override = g_spr_pal.hit_flash;
        actor->col.flash_clut_ticks--;
    }
    g_model_draw.target_frame = g_cur_render_frame;
    model_render_node(root, &identity);
    hierarchy_col_box_update(&actor->col, &actor->nodes[11], 4);
    g_model_draw.clut_override = 0;

    if (actor->attack_timer >= 0x201 && (g_render_state.frame & 0x7f) == 0 && actor->destruction_timer == 0)
    {
        PROJECTILE *projectile = projectile_create(projectile_origin->world_x, projectile_origin->world_y, projectile_origin->world_z, g_player_world.x, g_player_world.y - 0x2000u, g_player_world.z);
        projectile->col.hit.damage = 0x80;
        projectile->floor_callback = explosive_projectile_trail_update;
        projectile->impact_callback = explosive_projectile_impact;
        projectile->col.object_type = 0;
        projectile->col.receives_mask |= 4;
        projectile->motion.step.x = projectile->motion.step.x * 2u;
        projectile->motion.step.y = projectile->motion.step.y * 2u;
        projectile->motion.step.z = projectile->motion.step.z * 2u;
        sound_play_positional(10, 0, 0x96, actor->col.x, actor->col.y, actor->col.z);
        speech_random_request(10);
    }
    hud_bar_render(&g_boss_health_bar, actor->col.hit.health, 0, 0);
}

/* Original: AIRSHIP:AIRSHIP_800FB6C8. */
static void airship_damage(void *raw_actor, void *src)
{
    AIRSHIP_ACTOR *actor = (AIRSHIP_ACTOR *)raw_actor;
    if (actor->destruction_timer != 0)
        return;
    actor->col.flash_clut_ticks = 1;
    if (object_damage_apply(actor, src))
    {
        actor->destruction_timer = 1;
        speech_random_request(4);
        actor->attack_timer = 9999;
        expl_flash_create(actor->col.x, actor->col.y, actor->col.z - 0x2000u);
    }
}

/* Original: AIRSHIP:AIRSHIP_800FADD4. */
void airship_create(EFFECT *effect)
{
    AIRSHIP_ACTOR *actor = (AIRSHIP_ACTOR *)runtime_heap_allocate(sizeof(*actor));
    const sint16 *models = model_ids;
    sint32 n;
    effect->type = 0;
    actor->col.object.update = airship_update;
    linked_list_append(&g_object_list, actor);
    actor->col.object_type = 0x81;
    for (n = 0; n < 15; n++)
    {
        MODEL_NODE *node = &actor->nodes[n];
        actor->node_table[n] = node;
        node->model_id = models[n] == -1 ? 0 : models[n];
        node->pose_enabled = 0x3f;
    }
    actor->nodes[0].scale = 0x1000;
    model_pose_init(&initial_pose, actor->node_table, 15, 1);
    actor->col.x = effect->x;
    actor->col.y = effect->y - 0x4000;
    actor->col.z = effect->z - 0x3000;
    actor->col.hit_callback_kind = COLLISION_CALLBACK_NOTIFY;
    actor->col.hit_callback = airship_damage;
    actor->col.hit.health = 0x320;
    actor->col.receives_mask = 1;
    actor->base_y = actor->col.y;
    actor->min_x = actor->col.x - 0xc800;
    actor->max_x = actor->col.x + 0xc800;
    actor->target_velocity_x = 0x300;
    actor->target_yaw = 0x400;
    actor->attack_timer = 0x52c;
    hud_bar_initialize(&g_boss_health_bar, -0x28, -0x60, 0x50, 0x320);
}

