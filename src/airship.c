/* Exact 0x800A4C1C..0x800A4CD0. */
/* Original: FUN_800A4C1C. */
static void parachute_bomb_update(void *raw_o)
{
    SPRITE *o = (SPRITE *)raw_o;
    if (g_map_render.depth_anchor_z < o->col.z)
        object_destroy(o);
    if (o->animation.frame == 0x27804)
        o->velocity_y = 0x80;
    if (o->velocity_y == 0x80)
    {
        o->rotation_x = ((o->rotation_x + o->behavior.parachute_step) & 0x3ff);
        if (o->rotation_x >= 0x21 && o->rotation_x < 0x200)
            o->behavior.parachute_step = -2;
        if (o->rotation_x >= 0x201 && o->rotation_x < 0x3e0)
            o->behavior.parachute_step = 2;
    }
}

