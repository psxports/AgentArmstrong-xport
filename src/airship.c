static void airship_switch_activate(AIRSHIP_SWITCH *object)
{
    /* 800A5E04..800A5E10: three independent SH stores. A4 must not
     * overwrite the collision-activation flag at A6. */
    if (object->cooldown == 0)
    {
        object->cooldown = 0x3c;
        object->collision_latch = 1;
        object->input_latch = 0;
    }
}

/* Original: FUN_800A5B90. */
static void airship_switch_update(AIRSHIP_SWITCH *object)
{
    EFFECT *effect = object->effect;
    if (object->collision_latch == 0 && !world_object_is_visible(object->collision.x, object->collision.y, object->collision.z, 0x8000))
        return;
    if (object->cooldown != 0)
        object->cooldown--;
    if (!player_inside_xz_box(object->collision.x, object->collision.z, 0x4000, 0x2000) || !(g_held_buttons & 0x20) || g_player->menu_resume != 0 || object->cooldown != 0)
    {
        if (object->collision_latch == 0)
        {
            if (object->state != g_trigger_states[(uint16)effect->values[0]])
                goto toggle;
            object->input_latch = 0;
        }
        else
            goto perform;
    }
    else
    {
    toggle:
        if (object->collision_latch == 0 && object->state == g_trigger_states[(uint16)effect->values[0]])
        {
            /* 800A5C24 LH tests only the input latch; the adjacent grenade
             * timer at 1B6 is separate. 800A5CC0/CC4 clear/set via SH. */
            g_player->field_1b6 = 0;
            g_player->menu_resume = 1;
        }
    perform:
        object->collision_latch = 0;
        if (object->input_latch == 0)
        {
            sound_play_positional(0x17, 0, 0x7f, object->collision.x, object->collision.y, object->collision.z);
            object->state ^= 1;
            effect->values[1] = object->state;
            animation_start(&object->animation, (const sint32 *)player_assets_executable_address(object->state ? 0x800caee4u : 0x800caec8u));
        }
        object->input_latch = 1;
        object->cooldown = 0x3c;
    }
    animation_update(&object->animation);
    g_next_frame_object->light_delta = 0;
    if (g_stage_index != 0x0b)
        render_world_sprite(object->animation.frame, object->collision.x, object->collision.y, object->collision.z, 0, 0x1000, 0x1000, (POLY_FT4 *)object->collision.prim, 0, 0, 0, 0);
    g_trigger_states[(uint16)effect->values[0]] = (uint8)object->state;
}

