sint32 hq_interaction_prompt_update(const char *prompt, sint16 blocking_object_type)
{
    PLAYER *player = g_player;
    sint32 width;

    hq_prompt_latched = 1;
    if (hq_interaction_countdown != 0)
    {
        --hq_interaction_countdown;
        if (hq_interaction_countdown == 0)
            return 1;
    }

    player->field_22c &= ~0x40u;
    if (object_find_next_by_type(0, blocking_object_type) != 0)
        return 0;
    if ((g_pressed_buttons & 0x40) != 0)
    {
        hq_interaction_countdown = 2;
        return 0;
    }
    if ((g_held_buttons & 0x40) != 0)
        return 0;

    if ((g_frame_counter & 8) == 0)
        text_render((const char *)player_assets_executable_pointer(0x80082764u), -0x60, 0x40);
    width = text_byte_length(prompt) * g_font_glyph_width;
    text_render(prompt, -(width / 2), 0x50);
    return 0;
}

