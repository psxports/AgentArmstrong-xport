/* 0x8009EE30.  This is the integer DDA used by the original route renderer;
 * all values in line[] have eight fractional bits and the return value is
 * the number of one-world-unit steps along the dominant axis. */
/* Original: FUN_8009EE30. */
sint32 fixed_dda_initialize(sint32 x0, sint32 y0, sint32 z0, sint32 x1, sint32 y1, sint32 z1, sint32 *line)
{
    sint32 dx = (x1 - x0) * 0x100, dy = (y1 - y0) * 0x100, dz = (z1 - z0) * 0x100;
    sint32 ax = dx < 0 ? -dx : dx, ay = dy < 0 ? -dy : dy, az = dz < 0 ? -dz : dz, steps = ax >> 8;
    sint32 sx = 0, sy = 0, sz = 0;
    if (dx != 0)
    {
        sx = dx < 0 ? -0x10000 : 0x10000;
        sy = (dy / steps) << 8;
        sz = (dz / steps) << 8;
    }
    if ((ay >> 8) > steps)
    {
        steps = ay >> 8;
        sy = dy < 0 ? -0x10000 : 0x10000;
        sx = steps ? ((dx / steps) << 8) : 0;
        sz = steps ? ((dz / steps) << 8) : 0;
    }
    if ((az >> 8) > steps)
    {
        steps = az >> 8;
        sz = dz < 0 ? -0x10000 : 0x10000;
        sx = steps ? ((dx / steps) << 8) : 0;
        sy = steps ? ((dy / steps) << 8) : 0;
    }
    line[0] = x0 * 0x100;
    line[1] = y0 * 0x100;
    line[2] = z0 * 0x100;
    line[3] = sx;
    line[4] = sy;
    line[5] = sz;
    return steps;
}

