/* Original: SLES_004.74:FUN_80096B58 (0x80096B58..0x80096B94).
 * Resident helper shared by AIRSHIP/SCUBA callers, not an overlay copy.
 * MIPS writes CLUT at DAT_800D401C - 0x1A, unlike FUN_80096B28,
 * which writes the embedded primitive at object + 0x52. */
void object_hit_flash_apply(void *object_val)
{
    COLLISION *object = (COLLISION *)object_val;
    if (object->flash_clut_ticks != 0)
    {
        XASSERT(!(g_next_transient_prim == g_transient_prims));
        --object->flash_clut_ticks;
        POLY_FT4 *poly = g_next_transient_prim - 1;
        poly->p[0].attr = g_spr_pal.hit_flash;
    }
}

/* Original: SLES_004.74:FUN_80096B28. */
void object_embedded_hit_flash_apply(void *object_val)
{
    COLLISION *object = (COLLISION *)object_val;
    if (object->flash_clut_ticks != 0)
    {
        object->flash_clut_ticks = (object->flash_clut_ticks - 1);
        object->prim.p[0].attr = g_spr_pal.hit_flash;
    }
}

